%% Figure 5: Body-frame acceleration

figure_body_acceleration = figure( ...
    'Name', ...
    'Body-Frame Acceleration');

plot( ...
    truth.time, ...
    truth.acceleration_body_x, ...
    'LineWidth', ...
    1.5);

hold on;

plot( ...
    truth.time, ...
    truth.acceleration_body_y, ...
    'LineWidth', ...
    1.5);

grid on;

xlabel('Time [s]');
ylabel('Acceleration [m/s^2]');
title('Ground-Truth Body-Frame Acceleration');

legend( ...
    'Longitudinal acceleration, a_x^B', ...
    'Lateral acceleration, a_y^B', ...
    'Location', ...
    'best');

%% Figure 6: Yaw rate

figure_yaw_rate = figure( ...
    'Name', ...
    'Ground-Truth Yaw Rate');

plot( ...
    truth.time, ...
    rad2deg(truth.yaw_rate), ...
    'LineWidth', ...
    1.5);

grid on;

xlabel('Time [s]');
ylabel('Yaw rate [deg/s]');
title('Ground-Truth Yaw Rate');

%% Figure 7: Velocity components

figure_velocity = figure( ...
    'Name', ...
