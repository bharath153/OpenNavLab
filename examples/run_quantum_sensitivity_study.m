function reduced_quantum = select_quantum_measurement_rate( ...
    maximum_rate_quantum, ...
    requested_frequency, ...
    dt)
%SELECT_QUANTUM_MEASUREMENT_RATE Subsample a maximum-rate quantum sensor.
%
% The lower-rate dataset uses exactly the same measurements as the
% maximum-rate sensor whenever their measurement timestamps coincide.

    number_of_samples = ...
        numel(maximum_rate_quantum.time);

    samples_per_update_exact = ...
        1 / (requested_frequency * dt);

    samples_per_update = ...
        round(samples_per_update_exact);

    if abs(samples_per_update_exact - samples_per_update) > 1e-10
        error( ...
            'Requested quantum frequency is incompatible with dt.');
    end

    scheduled_mask = ...
        false(number_of_samples, 1);

    scheduled_indices = ...
        1:samples_per_update:number_of_samples;

    scheduled_mask(scheduled_indices) = true;

    if any( ...
            scheduled_mask ...
            & ~maximum_rate_quantum.scheduled_update_mask)

        error( ...
            ['The requested quantum rate is not an exact subset of ' ...
             'the maximum-rate quantum measurements.']);
    end

    reduced_quantum = ...
        maximum_rate_quantum;

    available_mask = ...
        scheduled_mask ...
        & maximum_rate_quantum.available_measurement_mask;

    measurement_fields = { ...
        'acceleration_x_measured', ...
        'acceleration_y_measured', ...
        'yaw_rate_measured', ...
        'acceleration_noise_x', ...
        'acceleration_noise_y', ...
        'gyroscope_noise', ...
        'acceleration_error_x', ...
        'acceleration_error_y', ...
        'yaw_rate_error', ...
        'acceleration_phase_true_x', ...
        'acceleration_phase_true_y', ...
        'acceleration_phase_measured_x', ...
        'acceleration_phase_measured_y', ...
        'acceleration_phase_error_x', ...
        'acceleration_phase_error_y'};

    for field_index = 1:numel(measurement_fields)

        current_field = ...
            measurement_fields{field_index};

        if ~isfield(reduced_quantum, current_field)
            continue;
        end

        current_values = ...
            reduced_quantum.(current_field);

        current_values(~available_mask) = NaN;

        reduced_quantum.(current_field) = ...
            current_values;
    end

    reduced_quantum.update_frequency = ...
        requested_frequency;

    reduced_quantum.update_period = ...
        1 / requested_frequency;

    reduced_quantum.samples_per_update = ...
        samples_per_update;

    reduced_quantum.scheduled_update_mask = ...
        scheduled_mask;

    reduced_quantum.available_measurement_mask = ...
        available_mask;

    reduced_quantum.valid_measurement_indices = ...
        find(available_mask);

    reduced_quantum.number_of_scheduled_updates = ...
        nnz(scheduled_mask);

    reduced_quantum.number_of_available_measurements = ...
        nnz(available_mask);

    if isfield(maximum_rate_quantum, 'outage_mask')

        reduced_quantum.number_of_suppressed_measurements = ...
            nnz(scheduled_mask & maximum_rate_quantum.outage_mask);

    else

        reduced_quantum.number_of_suppressed_measurements = ...
            nnz(scheduled_mask & ~available_mask);
    end

    if isfield(reduced_quantum, 'config')
        reduced_quantum.config.update_frequency = ...
            requested_frequency;
    end
end


function percentile_value = calculate_percentile( ...
    values, ...
    requested_percentile)
%CALCULATE_PERCENTILE Calculate a percentile without extra toolboxes.

    values = values(:);
    values = values(isfinite(values));

    if isempty(values)
        error('Cannot calculate a percentile from an empty vector.');
    end

    if requested_percentile < 0 ...
            || requested_percentile > 100

        error('Percentile must be between 0 and 100.');
    end

    sorted_values = sort(values);
    number_of_values = numel(sorted_values);

    if number_of_values == 1

        percentile_value = ...
            sorted_values(1);

        return;
    end

    fractional_index = ...
        1 ...
        + (number_of_values - 1) ...
        * requested_percentile ...
        / 100;

    lower_index = floor(fractional_index);
    upper_index = ceil(fractional_index);

    if lower_index == upper_index

        percentile_value = ...
            sorted_values(lower_index);

    else

        interpolation_fraction = ...
            fractional_index ...
            - lower_index;

        percentile_value = ...
            sorted_values(lower_index) ...
            + interpolation_fraction ...
            * ( ...
                sorted_values(upper_index) ...
                - sorted_values(lower_index));
    end
end


function [confidence_interval_lower, ...
          confidence_interval_upper] = ...
    calculate_mean_confidence_interval(values)
%CALCULATE_MEAN_CONFIDENCE_INTERVAL Approximate normal 95% CI.

    values = values(:);
    values = values(isfinite(values));

    if numel(values) < 2
        error('At least two values are required.');
    end

    sample_mean = ...
        mean(values);

    standard_error = ...
        std(values) ...
        / sqrt(numel(values));

    confidence_interval_lower = ...
        sample_mean ...
        - 1.96 * standard_error;

    confidence_interval_upper = ...
        sample_mean ...
        + 1.96 * standard_error;
end


function set_discrete_matrix_axes( ...
    outage_labels, ...
    quantum_labels, ...
    duration_positions, ...
    quantum_positions)
%SET_DISCRETE_MATRIX_AXES Format an imagesc plot as a discrete matrix.

    set( ...
        gca, ...
        'YDir', ...
        'normal', ...
        'XTick', ...
        duration_positions, ...
        'XTickLabel', ...
        outage_labels, ...
        'YTick', ...
        quantum_positions, ...
        'YTickLabel', ...
        quantum_labels);

    xlim( ...
        [ ...
            duration_positions(1) - 0.5, ...
            duration_positions(end) + 0.5]);

    ylim( ...
        [ ...
            quantum_positions(1) - 0.5, ...
            quantum_positions(end) + 0.5]);
end


function add_matrix_labels(matrix_values)
%ADD_MATRIX_LABELS Add formatted numerical values to an imagesc plot.

    [number_of_rows, number_of_columns] = ...
        size(matrix_values);

    current_colour_limits = ...
        clim;

    colour_midpoint = ...
        mean(current_colour_limits);

    hold on;

    for row_index = 1:number_of_rows

        for column_index = 1:number_of_columns

            current_value = ...
                matrix_values(row_index, column_index);

            if current_value >= colour_midpoint
                label_colour = [1, 1, 1];
            else
                label_colour = [0, 0, 0];
            end

            text( ...
                column_index, ...
                row_index, ...
                sprintf('%.1f', current_value), ...
                'HorizontalAlignment', ...
                'center', ...
                'VerticalAlignment', ...
                'middle', ...
                'FontWeight', ...
                'bold', ...
                'Color', ...
                label_colour);
        end
    end
end
