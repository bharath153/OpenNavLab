%% Generate deterministic ground truth

dt = 0.01;
simulation_time = 120;

truth = generate_truth_trajectory( ...
    dt, ...
    simulation_time);

%% Load configurations

base_imu_config = create_imu_config();
base_gps_config = create_gps_config();

nominal_quantum_config = ...
    create_quantum_sensor_config();

study_config = ...
    create_quantum_sensitivity_config();

number_of_runs = ...
    study_config.number_of_runs;

outage_start_time = ...
    study_config.outage_start_time;

outage_durations = ...
    study_config.outage_durations(:)';

outage_plot_labels = ...
    study_config.outage_plot_labels(:)';

quantum_update_frequencies = ...
    study_config.quantum_update_frequencies(:)';

quantum_frequency_plot_labels = ...
    compose('%.2g', quantum_update_frequencies);

number_of_durations = ...
    numel(outage_durations);

number_of_quantum_rates = ...
    numel(quantum_update_frequencies);

maximum_quantum_frequency = ...
    max(quantum_update_frequencies);

nominal_quantum_config.update_frequency = ...
    maximum_quantum_frequency;

nominal_quantum_config.outage_windows = [];

%% Validate study configuration

if number_of_runs < 2
    error('At least two Monte Carlo runs are required.');
end

if numel(outage_plot_labels) ~= number_of_durations
    error( ...
        ['The number of outage plot labels must match the number ' ...
         'of outage-duration cases.']);
end

if any(outage_durations < 0)
    error('GPS-outage durations cannot be negative.');
end

if any(diff(outage_durations) < 0)
    error('GPS-outage durations must be in ascending order.');
end

if outage_start_time + max(outage_durations) > truth.time(end)
    error('The longest GPS outage exceeds the simulation interval.');
end

if any(quantum_update_frequencies <= 0)
    error('Quantum update frequencies must be positive.');
end

if any(diff(quantum_update_frequencies) <= 0)
    error('Quantum update frequencies must be strictly increasing.');
end

for rate_index = 1:number_of_quantum_rates

    current_frequency = ...
        quantum_update_frequencies(rate_index);

    samples_per_update_exact = ...
        1 / (current_frequency * dt);

    samples_per_update = ...
        round(samples_per_update_exact);

    if abs(samples_per_update_exact - samples_per_update) > 1e-10
        error( ...
            ['Quantum rate %.3f Hz is incompatible with the ' ...
             'simulation time step.'], ...
            current_frequency);
    end

    maximum_to_current_ratio = ...
        maximum_quantum_frequency / current_frequency;

    if abs(maximum_to_current_ratio ...
            - round(maximum_to_current_ratio)) > 1e-10

        error( ...
            ['Quantum rate %.3f Hz is not an exact subdivision of ' ...
             'the maximum quantum rate.'], ...
            current_frequency);
    end
end

%% Reference indices and outage masks

reference_index = find( ...
    truth.time >= outage_start_time, ...
    1, ...
    'first');

if isempty(reference_index)
    error('The outage-start reference index was not found.');
end

outage_masks = ...
    false(numel(truth.time), number_of_durations);

interval_end_indices = ...
    nan(number_of_durations, 1);

for duration_index = 1:number_of_durations

    current_duration = ...
        outage_durations(duration_index);

    if current_duration == 0

        interval_end_indices(duration_index) = ...
            reference_index;

    else

        current_outage_end = ...
            outage_start_time + current_duration;

        outage_masks(:, duration_index) = ...
            truth.time >= outage_start_time ...
            & truth.time < current_outage_end;

        interval_end_indices(duration_index) = find( ...
            truth.time < current_outage_end, ...
            1, ...
            'last');

        if ~any(outage_masks(:, duration_index))
            error( ...
                'No samples were found for the %.1f-second outage.', ...
                current_duration);
        end
    end
end

%% Preallocate classical results
%
% Dimensions:
%   row    = Monte Carlo run
%   column = GPS-outage duration

classical_reference_or_maximum_error = ...
    nan(number_of_runs, number_of_durations);

classical_interval_end_error = ...
    nan(number_of_runs, number_of_durations);

classical_position_rmse = ...
    nan(number_of_runs, number_of_durations);

classical_velocity_rmse = ...
    nan(number_of_runs, number_of_durations);

classical_heading_rmse = ...
    nan(number_of_runs, number_of_durations);

classical_gps_mean_nis = ...
    nan(number_of_runs, number_of_durations);

classical_gps_nis_exceedance = ...
    nan(number_of_runs, number_of_durations);

classical_gps_update_count = ...
    nan(number_of_runs, number_of_durations);

%% Preallocate quantum-aided results
%
% Dimensions:
%   first dimension  = Monte Carlo run
%   second dimension = GPS-outage duration
%   third dimension  = quantum update frequency

result_size = [ ...
    number_of_runs, ...
    number_of_durations, ...
    number_of_quantum_rates];

quantum_reference_or_maximum_error = nan(result_size);
quantum_interval_end_error = nan(result_size);

quantum_position_rmse = nan(result_size);
quantum_velocity_rmse = nan(result_size);
quantum_heading_rmse = nan(result_size);

quantum_gps_mean_nis = nan(result_size);
quantum_update_mean_nis = nan(result_size);

quantum_gps_nis_exceedance = nan(result_size);
quantum_update_nis_exceedance = nan(result_size);

quantum_gps_update_count = nan(result_size);
quantum_update_count = nan(result_size);

%% Bias-estimation RMSE during each study interval

classical_accelerometer_x_bias_rmse = ...
    nan(number_of_runs, number_of_durations);

classical_accelerometer_y_bias_rmse = ...
    nan(number_of_runs, number_of_durations);

classical_gyroscope_bias_rmse = ...
    nan(number_of_runs, number_of_durations);

quantum_accelerometer_x_bias_rmse = nan(result_size);
quantum_accelerometer_y_bias_rmse = nan(result_size);
quantum_gyroscope_bias_rmse = nan(result_size);

expected_quantum_updates_by_rate = ...
    nan(1, number_of_quantum_rates);

%% Display study setup

total_filter_simulations = ...
    number_of_runs ...
    * number_of_durations ...
    * (1 + number_of_quantum_rates);

fprintf('\n');
fprintf('============================================================\n');
fprintf('OpenNavLab Phase 7D: Quantum Sensitivity Study\n');
fprintf('============================================================\n');

fprintf('Study: %s\n', study_config.study_name);
fprintf('Monte Carlo runs:                  %d\n', number_of_runs);

fprintf('GPS-outage durations:              ');
fprintf('%.0f ', outage_durations);
fprintf('s\n');

fprintf('Quantum update frequencies:        ');
fprintf('%.2f ', quantum_update_frequencies);
fprintf('Hz\n');

fprintf('Total filter simulations:          %d\n', ...
    total_filter_simulations);

fprintf('Simulation duration per case:      %.1f s\n', ...
    simulation_time);

fprintf('GPS-outage start time:             %.1f s\n', ...
    outage_start_time);

fprintf('MEMS frequency:                    %.1f Hz\n', ...
    1 / dt);

fprintf('GPS frequency:                     %.1f Hz\n', ...
    base_gps_config.update_frequency);

fprintf('\nRunning sensitivity study...\n');

study_timer = tic;

%% Monte Carlo loop

for current_run = 1:number_of_runs

    %% Generate common random initialization

    initialization_seed = ...
        study_config.initialization_seed_offset ...
        + current_run;

    rng(initialization_seed, 'twister');

    initial_position_error_x = ...
        study_config.initial_position_error_std_x ...
        * randn();

    initial_position_error_y = ...
        study_config.initial_position_error_std_y ...
        * randn();

    initial_velocity_error_x = ...
        study_config.initial_velocity_error_std_x ...
        * randn();

    initial_velocity_error_y = ...
        study_config.initial_velocity_error_std_y ...
        * randn();

    initial_heading_error = ...
        study_config.initial_heading_error_std ...
        * randn();

    mems_initial_bias_variation_x = ...
        study_config.mems_accelerometer_bias_variation_std_x ...
        * randn();

    mems_initial_bias_variation_y = ...
        study_config.mems_accelerometer_bias_variation_std_y ...
        * randn();

    mems_initial_gyro_bias_variation = ...
        study_config.mems_gyroscope_bias_variation_std ...
        * randn();

    quantum_calibration_error_x = ...
        study_config.quantum_accelerometer_calibration_error_std_x ...
        * randn();

    quantum_calibration_error_y = ...
        study_config.quantum_accelerometer_calibration_error_std_y ...
        * randn();

    quantum_gyro_calibration_error = ...
        study_config.quantum_gyroscope_calibration_error_std ...
        * randn();

    %% Simulate one common MEMS IMU for every study case

    imu_config = base_imu_config;

    imu_config.random_seed = ...
        study_config.imu_seed_offset ...
        + current_run;

    imu_config.accelerometer.initial_bias_x = ...
        base_imu_config.accelerometer.initial_bias_x ...
        + mems_initial_bias_variation_x;

    imu_config.accelerometer.initial_bias_y = ...
        base_imu_config.accelerometer.initial_bias_y ...
        + mems_initial_bias_variation_y;

    imu_config.gyroscope.initial_bias = ...
        base_imu_config.gyroscope.initial_bias ...
        + mems_initial_gyro_bias_variation;

    imu = simulate_imu( ...
        truth, ...
        imu_config);

    %% Simulate the maximum-rate quantum reference

    actual_quantum_config = ...
        nominal_quantum_config;

    actual_quantum_config.random_seed = ...
        study_config.quantum_seed_offset ...
        + current_run;

    actual_quantum_config.update_frequency = ...
        maximum_quantum_frequency;

    actual_quantum_config.accelerometer.initial_bias_x = ...
        nominal_quantum_config.accelerometer.initial_bias_x ...
        + quantum_calibration_error_x;

    actual_quantum_config.accelerometer.initial_bias_y = ...
        nominal_quantum_config.accelerometer.initial_bias_y ...
        + quantum_calibration_error_y;

    actual_quantum_config.gyroscope.initial_bias = ...
        nominal_quantum_config.gyroscope.initial_bias ...
        + quantum_gyro_calibration_error;

    maximum_rate_quantum = ...
        simulate_quantum_reference_imu( ...
            truth, ...
            actual_quantum_config);

    %% Build exact lower-rate quantum datasets

    quantum_by_rate = ...
        cell(number_of_quantum_rates, 1);

    for rate_index = 1:number_of_quantum_rates

        quantum_by_rate{rate_index} = ...
            select_quantum_measurement_rate( ...
                maximum_rate_quantum, ...
                quantum_update_frequencies(rate_index), ...
                dt);

        if current_run == 1
            expected_quantum_updates_by_rate(rate_index) = ...
                quantum_by_rate{rate_index} ...
                .number_of_available_measurements;
        end
    end

    %% Common imperfect initial state

    initial_state.position_x = ...
        truth.position_x(1) ...
        + initial_position_error_x;

    initial_state.position_y = ...
        truth.position_y(1) ...
        + initial_position_error_y;

    initial_state.velocity_x = ...
        truth.velocity_x(1) ...
        + initial_velocity_error_x;

    initial_state.velocity_y = ...
        truth.velocity_y(1) ...
        + initial_velocity_error_y;

    initial_heading_unwrapped = ...
        truth.heading(1) ...
        + initial_heading_error;

    initial_state.heading = atan2( ...
        sin(initial_heading_unwrapped), ...
        cos(initial_heading_unwrapped));

    initial_state.accelerometer_bias_x = 0;
    initial_state.accelerometer_bias_y = 0;
    initial_state.gyroscope_bias = 0;

    %% Evaluate every GPS-outage duration

    for duration_index = 1:number_of_durations

        current_duration = ...
            outage_durations(duration_index);

        current_outage_end = ...
            outage_start_time ...
            + current_duration;

        %% Generate paired GPS measurements

        gps_config = base_gps_config;

        gps_config.random_seed = ...
            study_config.gps_seed_offset ...
            + current_run;

        if current_duration == 0
            gps_config.outage_windows = [];
        else
            gps_config.outage_windows = ...
                [outage_start_time, current_outage_end];
        end

        gps = simulate_gps( ...
            truth, ...
            gps_config);

        %% Run classical GPS/MEMS EKF

        classical_config = create_ekf_config( ...
            imu_config, ...
            gps_config);

        classical_ekf = run_ekf_navigation( ...
            imu, ...
            gps, ...
            initial_state, ...
            classical_config);

        %% Classical navigation errors

        current_classical_position_error = hypot( ...
            classical_ekf.position_x - truth.position_x, ...
            classical_ekf.position_y - truth.position_y);

        current_classical_velocity_error = hypot( ...
            classical_ekf.velocity_x - truth.velocity_x, ...
            classical_ekf.velocity_y - truth.velocity_y);

        current_classical_heading_error = atan2( ...
            sin(classical_ekf.heading - truth.heading), ...
            cos(classical_ekf.heading - truth.heading));

        current_classical_heading_error_degrees = ...
            rad2deg(current_classical_heading_error);

        %% Classical reference or maximum outage error

        if current_duration == 0

            classical_reference_or_maximum_error( ...
                current_run, ...
                duration_index) = ...
                current_classical_position_error(reference_index);

            interval_mask = ...
                false(size(truth.time));

            interval_mask(reference_index) = true;

        else

            interval_mask = ...
                outage_masks(:, duration_index);

            classical_reference_or_maximum_error( ...
                current_run, ...
                duration_index) = ...
                max(current_classical_position_error(interval_mask));
        end

        current_interval_end_index = ...
            interval_end_indices(duration_index);

        classical_interval_end_error( ...
            current_run, ...
            duration_index) = ...
            current_classical_position_error( ...
                current_interval_end_index);

        classical_position_rmse( ...
            current_run, ...
            duration_index) = ...
            sqrt(mean(current_classical_position_error.^2));

        classical_velocity_rmse( ...
            current_run, ...
            duration_index) = ...
            sqrt(mean(current_classical_velocity_error.^2));

        classical_heading_rmse( ...
            current_run, ...
            duration_index) = ...
            sqrt(mean(current_classical_heading_error_degrees.^2));

        %% Classical bias-estimation RMSE over the study interval

        classical_bias_x_error = ...
            classical_ekf.accelerometer_bias_x ...
            - imu.accelerometer_bias_x;

        classical_bias_y_error = ...
            classical_ekf.accelerometer_bias_y ...
            - imu.accelerometer_bias_y;

        classical_gyro_bias_error_degrees = ...
            rad2deg( ...
                classical_ekf.gyroscope_bias ...
                - imu.gyroscope_bias);

        classical_accelerometer_x_bias_rmse( ...
            current_run, ...
            duration_index) = ...
            sqrt(mean(classical_bias_x_error(interval_mask).^2));

        classical_accelerometer_y_bias_rmse( ...
            current_run, ...
            duration_index) = ...
            sqrt(mean(classical_bias_y_error(interval_mask).^2));

        classical_gyroscope_bias_rmse( ...
            current_run, ...
            duration_index) = ...
            sqrt(mean( ...
                classical_gyro_bias_error_degrees(interval_mask).^2));

        %% Classical GPS innovation statistics

        valid_classical_gps_nis = ...
            classical_ekf.normalized_innovation_squared( ...
                classical_ekf.gps_update_applied);

        valid_classical_gps_nis = ...
            valid_classical_gps_nis( ...
                isfinite(valid_classical_gps_nis));

        if isempty(valid_classical_gps_nis)
            error( ...
                'No valid classical GPS innovations were found.');
        end

        classical_gps_mean_nis( ...
            current_run, ...
            duration_index) = ...
            mean(valid_classical_gps_nis);

        classical_gps_nis_exceedance( ...
            current_run, ...
            duration_index) = ...
            100 ...
            * nnz(valid_classical_gps_nis ...
                > study_config.gps_nis_95_threshold) ...
            / numel(valid_classical_gps_nis);

        classical_gps_update_count( ...
            current_run, ...
            duration_index) = ...
            classical_ekf.number_of_gps_updates;

        %% Evaluate all quantum update rates

        for rate_index = 1:number_of_quantum_rates

            current_quantum_frequency = ...
                quantum_update_frequencies(rate_index);

            current_quantum = ...
                quantum_by_rate{rate_index};

            filter_quantum_config = ...
                nominal_quantum_config;

            filter_quantum_config.update_frequency = ...
                current_quantum_frequency;

            quantum_aided_config = ...
                create_quantum_aided_ekf_config( ...
                    imu_config, ...
                    gps_config, ...
                    filter_quantum_config);

            quantum_aided_ekf = ...
                run_quantum_aided_ekf_navigation( ...
                    imu, ...
                    gps, ...
                    current_quantum, ...
                    initial_state, ...
                    quantum_aided_config);

            %% Quantum-aided navigation errors

            current_quantum_position_error = hypot( ...
                quantum_aided_ekf.position_x - truth.position_x, ...
                quantum_aided_ekf.position_y - truth.position_y);

            current_quantum_velocity_error = hypot( ...
                quantum_aided_ekf.velocity_x - truth.velocity_x, ...
                quantum_aided_ekf.velocity_y - truth.velocity_y);

            current_quantum_heading_error = atan2( ...
                sin(quantum_aided_ekf.heading - truth.heading), ...
                cos(quantum_aided_ekf.heading - truth.heading));

            current_quantum_heading_error_degrees = ...
                rad2deg(current_quantum_heading_error);

            %% Quantum reference or maximum outage error

            if current_duration == 0

                quantum_reference_or_maximum_error( ...
                    current_run, ...
                    duration_index, ...
                    rate_index) = ...
                    current_quantum_position_error(reference_index);

            else

                quantum_reference_or_maximum_error( ...
                    current_run, ...
                    duration_index, ...
                    rate_index) = ...
                    max(current_quantum_position_error(interval_mask));
            end

            quantum_interval_end_error( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                current_quantum_position_error( ...
                    current_interval_end_index);

            quantum_position_rmse( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                sqrt(mean(current_quantum_position_error.^2));

            quantum_velocity_rmse( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                sqrt(mean(current_quantum_velocity_error.^2));

            quantum_heading_rmse( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                sqrt(mean(current_quantum_heading_error_degrees.^2));

            %% Quantum-aided bias-estimation RMSE

            quantum_bias_x_error = ...
                quantum_aided_ekf.accelerometer_bias_x ...
                - imu.accelerometer_bias_x;

            quantum_bias_y_error = ...
                quantum_aided_ekf.accelerometer_bias_y ...
                - imu.accelerometer_bias_y;

            quantum_gyro_bias_error_degrees = ...
                rad2deg( ...
                    quantum_aided_ekf.gyroscope_bias ...
                    - imu.gyroscope_bias);

            quantum_accelerometer_x_bias_rmse( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                sqrt(mean(quantum_bias_x_error(interval_mask).^2));

            quantum_accelerometer_y_bias_rmse( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                sqrt(mean(quantum_bias_y_error(interval_mask).^2));

            quantum_gyroscope_bias_rmse( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                sqrt(mean( ...
                    quantum_gyro_bias_error_degrees(interval_mask).^2));

            %% Innovation statistics

            valid_quantum_gps_nis = ...
                quantum_aided_ekf ...
                .gps_normalized_innovation_squared( ...
                    quantum_aided_ekf.gps_update_applied);

            valid_quantum_gps_nis = ...
                valid_quantum_gps_nis( ...
                    isfinite(valid_quantum_gps_nis));

            valid_quantum_update_nis = ...
                quantum_aided_ekf ...
                .quantum_normalized_innovation_squared( ...
                    quantum_aided_ekf.quantum_update_applied);

            valid_quantum_update_nis = ...
                valid_quantum_update_nis( ...
                    isfinite(valid_quantum_update_nis));

            if isempty(valid_quantum_gps_nis)
                error( ...
                    'No valid quantum-aided GPS innovations were found.');
            end

            if isempty(valid_quantum_update_nis)
                error( ...
                    'No valid quantum innovations were found.');
            end

            quantum_gps_mean_nis( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                mean(valid_quantum_gps_nis);

            quantum_update_mean_nis( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                mean(valid_quantum_update_nis);

            quantum_gps_nis_exceedance( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                100 ...
                * nnz(valid_quantum_gps_nis ...
                    > study_config.gps_nis_95_threshold) ...
                / numel(valid_quantum_gps_nis);

            quantum_update_nis_exceedance( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                100 ...
                * nnz(valid_quantum_update_nis ...
                    > study_config.quantum_nis_95_threshold) ...
                / numel(valid_quantum_update_nis);

            quantum_gps_update_count( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                quantum_aided_ekf.number_of_gps_updates;

            quantum_update_count( ...
                current_run, ...
                duration_index, ...
                rate_index) = ...
                quantum_aided_ekf.number_of_quantum_updates;
        end
    end

    %% Progress report

    if mod( ...
            current_run, ...
            study_config.progress_report_interval) == 0 ...
            || current_run == number_of_runs

        elapsed_time = toc(study_timer);

        fprintf( ...
            ['  Completed %d of %d Monte Carlo runs ' ...
             '— elapsed %.1f s\n'], ...
            current_run, ...
            number_of_runs, ...
            elapsed_time);
    end
end

total_execution_time = toc(study_timer);

%% Calculate paired improvements

absolute_error_reduction = nan(result_size);
relative_error_reduction_percent = nan(result_size);

position_rmse_reduction_percent = nan(result_size);
velocity_rmse_reduction_percent = nan(result_size);
heading_rmse_reduction_percent = nan(result_size);

for rate_index = 1:number_of_quantum_rates

    absolute_error_reduction(:, :, rate_index) = ...
        classical_reference_or_maximum_error ...
        - quantum_reference_or_maximum_error(:, :, rate_index);

    relative_error_reduction_percent(:, :, rate_index) = ...
        100 ...
        * absolute_error_reduction(:, :, rate_index) ...
        ./ max(classical_reference_or_maximum_error, eps);

    position_rmse_reduction_percent(:, :, rate_index) = ...
        100 ...
        * (classical_position_rmse ...
        - quantum_position_rmse(:, :, rate_index)) ...
        ./ max(classical_position_rmse, eps);

    velocity_rmse_reduction_percent(:, :, rate_index) = ...
        100 ...
        * (classical_velocity_rmse ...
        - quantum_velocity_rmse(:, :, rate_index)) ...
