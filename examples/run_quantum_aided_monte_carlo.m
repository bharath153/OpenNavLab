        outage_end_time > truth.time(end)

    error( ...
        'The GPS outage lies outside the simulation interval.');
end

outage_mask = ...
    truth.time >= outage_start_time ...
    & truth.time < outage_end_time;

last_outage_index = find( ...
    outage_mask, ...
    1, ...
    'last');

if isempty(last_outage_index)

    error( ...
        'No samples were found inside the GPS outage.');
end

