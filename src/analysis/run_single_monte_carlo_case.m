function result = run_single_monte_carlo_case( ...
    truth, ...
    base_imu_config, ...
    base_gps_config, ...
    monte_carlo_config, ...
    run_number)
%RUN_SINGLE_MONTE_CARLO_CASE Execute one GPS/IMU EKF simulation.
%
% Inputs:
%   truth               - Common deterministic ground-truth trajectory
%   base_imu_config     - Nominal IMU configuration
%   base_gps_config     - Nominal GPS configuration
%   monte_carlo_config  - Monte Carlo configuration
%   run_number          - Current Monte Carlo run number
%
% Output:
%   result - Scalar performance metrics for the current run

    validateattributes( ...
        run_number, ...
        {'numeric'}, ...
        {'scalar', 'integer', 'positive'});

    %% Create independent random seeds

    initialization_seed = ...
        monte_carlo_config.initialization_seed_offset ...
        + run_number;

    imu_seed = ...
        monte_carlo_config.imu_seed_offset ...
        + run_number;

    gps_seed = ...
        monte_carlo_config.gps_seed_offset ...
        + run_number;

    %% Generate run-specific initialization errors

    rng(initialization_seed, 'twister');

    initial_position_error_x = ...
        monte_carlo_config.initial_position_error_std_x ...
        * randn();

    initial_position_error_y = ...
        monte_carlo_config.initial_position_error_std_y ...
        * randn();

    initial_velocity_error_x = ...
        monte_carlo_config.initial_velocity_error_std_x ...
        * randn();

    initial_velocity_error_y = ...
        monte_carlo_config.initial_velocity_error_std_y ...
        * randn();

    initial_heading_error = ...
        monte_carlo_config.initial_heading_error_std ...
        * randn();

    true_accelerometer_bias_variation_x = ...
        monte_carlo_config ...
        .true_accelerometer_bias_variation_std_x ...
        * randn();

    true_accelerometer_bias_variation_y = ...
        monte_carlo_config ...
        .true_accelerometer_bias_variation_std_y ...
        * randn();

    true_gyroscope_bias_variation = ...
        monte_carlo_config ...
        .true_gyroscope_bias_variation_std ...
        * randn();

    %% Create run-specific IMU configuration

    imu_config = base_imu_config;

    imu_config.random_seed = imu_seed;

    imu_config.accelerometer.initial_bias_x = ...
        base_imu_config.accelerometer.initial_bias_x ...
        + true_accelerometer_bias_variation_x;

    imu_config.accelerometer.initial_bias_y = ...
        base_imu_config.accelerometer.initial_bias_y ...
        + true_accelerometer_bias_variation_y;

    imu_config.gyroscope.initial_bias = ...
        base_imu_config.gyroscope.initial_bias ...
        + true_gyroscope_bias_variation;

    %% Create run-specific GPS configuration

    gps_config = base_gps_config;
    gps_config.random_seed = gps_seed;

    %% Simulate sensors

    imu = simulate_imu( ...
        truth, ...
        imu_config);

    gps = simulate_gps( ...
        truth, ...
        gps_config);

    %% Configure EKF

    ekf_config = create_ekf_config( ...
        imu_config, ...
        gps_config);

    %% Create imperfect initial navigation estimate

    initial_state.position_x = ...
        truth.position_x(1) ...
        + initial_position_error_x;

    initial_state.position_y = ...
        truth.position_y(1) ...
        + initial_position_error_y;

    initial_state.velocity_x = ...
        truth.velocity_x(1) ...
        + initial_velocity_error_x;

    initial_state.velocity_y = ...
        truth.velocity_y(1) ...
        + initial_velocity_error_y;

    initial_heading_unwrapped = ...
        truth.heading(1) ...
        + initial_heading_error;

    initial_state.heading = atan2( ...
        sin(initial_heading_unwrapped), ...
        cos(initial_heading_unwrapped));

    % The EKF is not given the true sensor biases.
    initial_state.accelerometer_bias_x = 0;
    initial_state.accelerometer_bias_y = 0;
    initial_state.gyroscope_bias = 0;

    %% Run EKF

    ekf = run_ekf_navigation( ...
        imu, ...
        gps, ...
        initial_state, ...
        ekf_config);

    %% Navigation errors

    position_error = hypot( ...
        ekf.position_x - truth.position_x, ...
        ekf.position_y - truth.position_y);

    velocity_error = hypot( ...
        ekf.velocity_x - truth.velocity_x, ...
        ekf.velocity_y - truth.velocity_y);

    heading_error = atan2( ...
        sin(ekf.heading - truth.heading), ...
        cos(ekf.heading - truth.heading));

    heading_error_degrees = ...
        rad2deg(heading_error);

    %% GPS outage indices

    outage_start = ...
        gps_config.outage_windows(1, 1);

    outage_end = ...
        gps_config.outage_windows(1, 2);

    outage_mask = ...
        truth.time >= outage_start ...
        & truth.time < outage_end;

    last_outage_index = find( ...
        truth.time < outage_end, ...
        1, ...
        'last');

    first_recovery_index = find( ...
        truth.time >= outage_end, ...
        1, ...
        'first');

    if isempty(last_outage_index) || ...
            isempty(first_recovery_index)

        error( ...
            'Could not determine GPS outage recovery indices.');
    end

    %% GPS outage performance

    maximum_outage_position_error = ...
        max(position_error(outage_mask));

    position_error_before_gps_return = ...
        position_error(last_outage_index);

    position_error_after_gps_return = ...
        position_error(first_recovery_index);

    recovery_error_reduction = ...
        position_error_before_gps_return ...
        - position_error_after_gps_return;

    if position_error_before_gps_return > 0

        recovery_error_reduction_percent = ...
            100 ...
            * recovery_error_reduction ...
            / position_error_before_gps_return;

    else

        recovery_error_reduction_percent = 0;
    end

    %% NIS statistics

    valid_nis = ...
        ekf.normalized_innovation_squared( ...
            ekf.gps_update_applied);

    mean_nis = mean(valid_nis);

    nis_exceedance_percentage = ...
        100 ...
        * nnz( ...
            valid_nis ...
            > monte_carlo_config.nis_95_threshold) ...
        / numel(valid_nis);

    %% Final bias-estimation errors

    final_accelerometer_bias_x_error = ...
        ekf.accelerometer_bias_x(end) ...
        - imu.accelerometer_bias_x(end);

    final_accelerometer_bias_y_error = ...
        ekf.accelerometer_bias_y(end) ...
        - imu.accelerometer_bias_y(end);

    final_gyroscope_bias_error = ...
        ekf.gyroscope_bias(end) ...
        - imu.gyroscope_bias(end);

    %% Store scalar results

    result.run_number = run_number;

    result.imu_seed = imu_seed;
    result.gps_seed = gps_seed;
    result.initialization_seed = initialization_seed;

    result.final_position_error = ...
        position_error(end);

    result.position_rmse = ...
        sqrt(mean(position_error.^2));

    result.maximum_position_error = ...
        max(position_error);

    result.final_velocity_error = ...
        velocity_error(end);

    result.velocity_rmse = ...
        sqrt(mean(velocity_error.^2));

    result.final_heading_error_absolute = ...
        abs(heading_error_degrees(end));

    result.heading_rmse = ...
        sqrt(mean(heading_error_degrees.^2));

    result.maximum_outage_position_error = ...
        maximum_outage_position_error;

    result.position_error_before_gps_return = ...
        position_error_before_gps_return;

    result.position_error_after_gps_return = ...
        position_error_after_gps_return;

    result.recovery_error_reduction = ...
        recovery_error_reduction;

    result.recovery_error_reduction_percent = ...
        recovery_error_reduction_percent;

    result.mean_nis = mean_nis;

    result.nis_exceedance_percentage = ...
        nis_exceedance_percentage;

    result.final_accelerometer_bias_x_error = ...
        final_accelerometer_bias_x_error;

    result.final_accelerometer_bias_y_error = ...
        final_accelerometer_bias_y_error;

    result.final_gyroscope_bias_error_deg_per_second = ...
        rad2deg(final_gyroscope_bias_error);

    result.initial_position_error_magnitude = hypot( ...
        initial_position_error_x, ...
        initial_position_error_y);

    result.initial_velocity_error_magnitude = hypot( ...
        initial_velocity_error_x, ...
        initial_velocity_error_y);

    result.initial_heading_error_absolute_degrees = ...
        abs(rad2deg(initial_heading_error));

    result.true_initial_accelerometer_bias_x = ...
        imu.accelerometer_bias_x(1);

    result.true_initial_accelerometer_bias_y = ...
        imu.accelerometer_bias_y(1);

    result.true_initial_gyroscope_bias_deg_per_second = ...
        rad2deg(imu.gyroscope_bias(1));

    result.number_of_gps_updates = ...
        ekf.number_of_gps_updates;
end