function ekf = run_quantum_aided_ekf_navigation( ...
    imu, ...
    gps, ...
    quantum, ...
    initial_state, ...
    config)
%RUN_QUANTUM_AIDED_EKF_NAVIGATION Run the GPS/MEMS/quantum EKF.
%
% State vector:
%
%   x = [px, py, vx, vy, psi, bax, bay, bg]'
%
% Sensor architecture:
%
%   MEMS IMU:
%       High-rate navigation propagation.
%
%   Quantum inertial reference:
%       Low-rate direct observation of MEMS accelerometer and gyroscope
%       biases.
%
%   GPS:
%       Position correction whenever GPS is available.
%
% The quantum phase output is not used directly here. Phase 7A assumes
% that atom-interferometer fringe order has already been resolved and
% provides unwrapped acceleration and yaw-rate measurements.

    %% State indices

    PX = config.index.position_x;
    PY = config.index.position_y;

    VX = config.index.velocity_x;
    VY = config.index.velocity_y;

    PSI = config.index.heading;

    BAX = config.index.accelerometer_bias_x;
    BAY = config.index.accelerometer_bias_y;

    BG = config.index.gyroscope_bias;

    number_of_states = config.number_of_states;

    %% Validate time vectors

    time = imu.time(:);
    number_of_samples = numel(time);

    if number_of_samples < 2
        error('At least two IMU samples are required.');
    end

    if numel(gps.time) ~= number_of_samples
        error('GPS and IMU data lengths are inconsistent.');
    end

    if numel(quantum.time) ~= number_of_samples
        error('Quantum and IMU data lengths are inconsistent.');
    end

    if max(abs(gps.time(:) - time)) > 1e-12
        error('GPS and IMU time vectors are inconsistent.');
    end

    if max(abs(quantum.time(:) - time)) > 1e-12
        error('Quantum and IMU time vectors are inconsistent.');
    end

    %% Validate measurement lengths

    measurement_vectors = { ...
        imu.acceleration_x_measured, ...
        imu.acceleration_y_measured, ...
        imu.yaw_rate_measured, ...
        gps.position_x_measured, ...
        gps.position_y_measured, ...
        quantum.acceleration_x_measured, ...
        quantum.acceleration_y_measured, ...
        quantum.yaw_rate_measured};

    for vector_index = 1:numel(measurement_vectors)

        if numel(measurement_vectors{vector_index}) ~= number_of_samples
            error('A sensor vector has an incorrect length.');
        end
    end

    %% Validate initial state

    required_initial_fields = { ...
        'position_x', ...
        'position_y', ...
        'velocity_x', ...
        'velocity_y', ...
        'heading', ...
        'accelerometer_bias_x', ...
        'accelerometer_bias_y', ...
        'gyroscope_bias'};

    for field_index = 1:numel(required_initial_fields)

        current_field = required_initial_fields{field_index};

        if ~isfield(initial_state, current_field)

            error( ...
                'Initial state is missing the field "%s".', ...
                current_field);
        end
    end

    %% Preallocate state and covariance histories

    state_estimate = ...
        zeros(number_of_states, number_of_samples);

    covariance_history = ...
        zeros( ...
            number_of_states, ...
            number_of_states, ...
            number_of_samples);

    covariance_standard_deviation = ...
        zeros(number_of_states, number_of_samples);

    %% GPS diagnostics

    gps_innovation = ...
        nan(2, number_of_samples);

    gps_innovation_covariance = ...
        nan(2, 2, number_of_samples);

    gps_nis = ...
        nan(number_of_samples, 1);

    gps_update_applied = ...
        false(number_of_samples, 1);

    %% Quantum diagnostics

    quantum_bias_measurement = ...
        nan(3, number_of_samples);

    quantum_innovation = ...
        nan(3, number_of_samples);

    quantum_innovation_covariance = ...
        nan(3, 3, number_of_samples);

    quantum_nis = ...
        nan(number_of_samples, 1);

    quantum_update_applied = ...
        false(number_of_samples, 1);

    %% Initial state

    state_estimate(:, 1) = ...
        [initial_state.position_x; ...
         initial_state.position_y; ...
         initial_state.velocity_x; ...
         initial_state.velocity_y; ...
         initial_state.heading; ...
         initial_state.accelerometer_bias_x; ...
         initial_state.accelerometer_bias_y; ...
         initial_state.gyroscope_bias];

    covariance = config.initial_covariance;

    %% GPS measurement matrix

    gps_measurement_matrix = ...
        zeros(2, number_of_states);

    gps_measurement_matrix(1, PX) = 1;
    gps_measurement_matrix(2, PY) = 1;

    %% Quantum bias-observation matrix

    quantum_measurement_matrix = ...
        zeros(3, number_of_states);

    quantum_measurement_matrix(1, BAX) = 1;
    quantum_measurement_matrix(2, BAY) = 1;
    quantum_measurement_matrix(3, BG) = 1;

    %% Initial quantum update

    if quantum.available_measurement_mask(1)

        [quantum_measurement, ...
         quantum_measurement_covariance] = ...
            create_quantum_bias_measurement( ...
                imu, ...
                quantum, ...
                1, ...
                time(1), ...
                config);

        [state_estimate(:, 1), ...
         covariance, ...
         quantum_innovation(:, 1), ...
         quantum_innovation_covariance(:, :, 1), ...
         quantum_nis(1)] = ...
            apply_linear_measurement_update( ...
                state_estimate(:, 1), ...
                covariance, ...
                quantum_measurement, ...
                quantum_measurement_matrix, ...
                quantum_measurement_covariance, ...
                config.use_joseph_covariance_update);

        quantum_bias_measurement(:, 1) = ...
            quantum_measurement;

        quantum_update_applied(1) = true;
    end

    %% Initial GPS update

    if gps.available_measurement_mask(1)

        gps_measurement = ...
            [gps.position_x_measured(1); ...
             gps.position_y_measured(1)];

        [state_estimate(:, 1), ...
         covariance, ...
         gps_innovation(:, 1), ...
         gps_innovation_covariance(:, :, 1), ...
         gps_nis(1)] = ...
            apply_linear_measurement_update( ...
                state_estimate(:, 1), ...
                covariance, ...
                gps_measurement, ...
                gps_measurement_matrix, ...
                config.gps_measurement_covariance, ...
                config.use_joseph_covariance_update);

        gps_update_applied(1) = true;
    end

    covariance = ...
        0.5 * (covariance + covariance');

    covariance_history(:, :, 1) = ...
        covariance;

    %% Prediction and measurement-update loop

    for k = 1:number_of_samples - 1

        dt = time(k + 1) - time(k);

        if dt <= 0
            error('The time vector must be strictly increasing.');
        end

        %% MEMS prediction

        [predicted_state, ...
         predicted_covariance] = ...
            predict_navigation_state( ...
                state_estimate(:, k), ...
                covariance, ...
                imu, ...
                k, ...
                dt, ...
                config);

        corrected_state = ...
            predicted_state;

        corrected_covariance = ...
            predicted_covariance;

        %% Quantum MEMS-bias correction

        if quantum.available_measurement_mask(k + 1)

            [quantum_measurement, ...
             quantum_measurement_covariance] = ...
                create_quantum_bias_measurement( ...
                    imu, ...
                    quantum, ...
                    k + 1, ...
                    time(k + 1), ...
                    config);

            [corrected_state, ...
             corrected_covariance, ...
             quantum_innovation(:, k + 1), ...
             quantum_innovation_covariance(:, :, k + 1), ...
             quantum_nis(k + 1)] = ...
                apply_linear_measurement_update( ...
                    corrected_state, ...
                    corrected_covariance, ...
                    quantum_measurement, ...
                    quantum_measurement_matrix, ...
                    quantum_measurement_covariance, ...
                    config.use_joseph_covariance_update);

            quantum_bias_measurement(:, k + 1) = ...
                quantum_measurement;

            quantum_update_applied(k + 1) = true;
        end

        %% GPS position correction

        if gps.available_measurement_mask(k + 1)

            gps_measurement = ...
                [gps.position_x_measured(k + 1); ...
                 gps.position_y_measured(k + 1)];

            [corrected_state, ...
             corrected_covariance, ...
             gps_innovation(:, k + 1), ...
             gps_innovation_covariance(:, :, k + 1), ...
             gps_nis(k + 1)] = ...
                apply_linear_measurement_update( ...
                    corrected_state, ...
                    corrected_covariance, ...
                    gps_measurement, ...
                    gps_measurement_matrix, ...
                    config.gps_measurement_covariance, ...
                    config.use_joseph_covariance_update);

            gps_update_applied(k + 1) = true;
        end

        %% Store corrected state

        corrected_state(PSI) = atan2( ...
            sin(corrected_state(PSI)), ...
            cos(corrected_state(PSI)));

        corrected_covariance = ...
            0.5 ...
            * (corrected_covariance ...
            + corrected_covariance');

        state_estimate(:, k + 1) = ...
            corrected_state;

        covariance = ...
            corrected_covariance;

        covariance_history(:, :, k + 1) = ...
            covariance;
    end

    %% Extract covariance standard deviations

    for k = 1:number_of_samples

        covariance_diagonal = ...
            diag(covariance_history(:, :, k));

        covariance_diagonal = ...
            max(covariance_diagonal, 0);

        covariance_standard_deviation(:, k) = ...
            sqrt(covariance_diagonal);
    end

    %% Store outputs

    ekf.time = time;
    ekf.state_estimate = state_estimate;

    ekf.position_x = state_estimate(PX, :)';
    ekf.position_y = state_estimate(PY, :)';

    ekf.velocity_x = state_estimate(VX, :)';
    ekf.velocity_y = state_estimate(VY, :)';

    ekf.speed = hypot( ...
        ekf.velocity_x, ...
        ekf.velocity_y);

    ekf.heading = state_estimate(PSI, :)';

    ekf.accelerometer_bias_x = ...
        state_estimate(BAX, :)';

    ekf.accelerometer_bias_y = ...
        state_estimate(BAY, :)';

    ekf.gyroscope_bias = ...
        state_estimate(BG, :)';

    ekf.covariance_history = ...
        covariance_history;

    ekf.covariance_standard_deviation = ...
        covariance_standard_deviation;

    ekf.gps_innovation = ...
        gps_innovation;

    ekf.gps_innovation_covariance = ...
        gps_innovation_covariance;

    ekf.gps_normalized_innovation_squared = ...
        gps_nis;

    ekf.gps_update_applied = ...
        gps_update_applied;

    ekf.quantum_bias_measurement = ...
        quantum_bias_measurement;

    ekf.quantum_innovation = ...
        quantum_innovation;

    ekf.quantum_innovation_covariance = ...
        quantum_innovation_covariance;

    ekf.quantum_normalized_innovation_squared = ...
        quantum_nis;

    ekf.quantum_update_applied = ...
        quantum_update_applied;

    ekf.number_of_gps_updates = ...
        nnz(gps_update_applied);

    ekf.number_of_quantum_updates = ...
        nnz(quantum_update_applied);

    ekf.config = config;
end


function [predicted_state, predicted_covariance] = ...
    predict_navigation_state( ...
        current_state, ...
        current_covariance, ...
        imu, ...
        sample_index, ...
        dt, ...
        config)
%PREDICT_NAVIGATION_STATE Perform one nonlinear MEMS propagation step.

    PX = config.index.position_x;
    PY = config.index.position_y;

    VX = config.index.velocity_x;
    VY = config.index.velocity_y;

    PSI = config.index.heading;

    BAX = config.index.accelerometer_bias_x;
    BAY = config.index.accelerometer_bias_y;

    BG = config.index.gyroscope_bias;

    number_of_states = config.number_of_states;

    position_x = current_state(PX);
    position_y = current_state(PY);

    velocity_x = current_state(VX);
    velocity_y = current_state(VY);

    heading = current_state(PSI);

    accelerometer_bias_x = current_state(BAX);
    accelerometer_bias_y = current_state(BAY);

    gyroscope_bias = current_state(BG);

    %% Bias-corrected MEMS measurements

    acceleration_body_x = ...
        imu.acceleration_x_measured(sample_index) ...
        - accelerometer_bias_x;

    acceleration_body_y = ...
        imu.acceleration_y_measured(sample_index) ...
        - accelerometer_bias_y;

    corrected_yaw_rate = ...
        imu.yaw_rate_measured(sample_index) ...
        - gyroscope_bias;

    %% Rotate acceleration into navigation coordinates

    cosine_heading = cos(heading);
    sine_heading = sin(heading);

    rotation_body_to_navigation = ...
        [cosine_heading, -sine_heading; ...
         sine_heading,  cosine_heading];

    acceleration_navigation = ...
        rotation_body_to_navigation ...
        * [acceleration_body_x; ...
           acceleration_body_y];

    acceleration_navigation_x = ...
        acceleration_navigation(1);

    acceleration_navigation_y = ...
        acceleration_navigation(2);

    %% Nonlinear state prediction

    predicted_state = current_state;

    predicted_state(PX) = ...
        position_x ...
        + velocity_x * dt ...
        + 0.5 * acceleration_navigation_x * dt^2;

    predicted_state(PY) = ...
        position_y ...
        + velocity_y * dt ...
        + 0.5 * acceleration_navigation_y * dt^2;

    predicted_state(VX) = ...
        velocity_x ...
        + acceleration_navigation_x * dt;

    predicted_state(VY) = ...
        velocity_y ...
        + acceleration_navigation_y * dt;

    predicted_heading = ...
        heading ...
        + corrected_yaw_rate * dt;

    predicted_state(PSI) = atan2( ...
        sin(predicted_heading), ...
        cos(predicted_heading));

    predicted_state(BAX) = accelerometer_bias_x;
    predicted_state(BAY) = accelerometer_bias_y;
    predicted_state(BG) = gyroscope_bias;

    %% State-transition Jacobian

    acceleration_x_heading_derivative = ...
        -sine_heading * acceleration_body_x ...
        -cosine_heading * acceleration_body_y;

    acceleration_y_heading_derivative = ...
         cosine_heading * acceleration_body_x ...
        -sine_heading * acceleration_body_y;

    state_transition_jacobian = ...
        eye(number_of_states);

    state_transition_jacobian(PX, VX) = dt;
    state_transition_jacobian(PY, VY) = dt;

    state_transition_jacobian(PX, PSI) = ...
        0.5 ...
        * acceleration_x_heading_derivative ...
        * dt^2;

    state_transition_jacobian(PY, PSI) = ...
        0.5 ...
        * acceleration_y_heading_derivative ...
        * dt^2;

    state_transition_jacobian(VX, PSI) = ...
        acceleration_x_heading_derivative * dt;

    state_transition_jacobian(VY, PSI) = ...
        acceleration_y_heading_derivative * dt;

    state_transition_jacobian(PX, BAX) = ...
        -0.5 * cosine_heading * dt^2;

    state_transition_jacobian(PX, BAY) = ...
         0.5 * sine_heading * dt^2;

    state_transition_jacobian(PY, BAX) = ...
        -0.5 * sine_heading * dt^2;

    state_transition_jacobian(PY, BAY) = ...
        -0.5 * cosine_heading * dt^2;

    state_transition_jacobian(VX, BAX) = ...
        -cosine_heading * dt;

    state_transition_jacobian(VX, BAY) = ...
         sine_heading * dt;

    state_transition_jacobian(VY, BAX) = ...
        -sine_heading * dt;

    state_transition_jacobian(VY, BAY) = ...
        -cosine_heading * dt;

    state_transition_jacobian(PSI, BG) = ...
        -dt;

    %% Process-noise mapping

    noise_mapping = ...
        zeros(number_of_states, 6);

    noise_mapping( ...
        [PX, PY], ...
        [1, 2]) = ...
        0.5 ...
        * rotation_body_to_navigation ...
        * dt^2;

    noise_mapping( ...
        [VX, VY], ...
        [1, 2]) = ...
        rotation_body_to_navigation ...
        * dt;

    noise_mapping(PSI, 3) = dt;

    noise_mapping(BAX, 4) = 1;
    noise_mapping(BAY, 5) = 1;
    noise_mapping(BG, 6) = 1;

    accelerometer_bias_increment_std_x = ...
        config.accelerometer_bias_random_walk_std_x ...
        * sqrt(dt);

    accelerometer_bias_increment_std_y = ...
        config.accelerometer_bias_random_walk_std_y ...
        * sqrt(dt);

    gyroscope_bias_increment_std = ...
        config.gyroscope_bias_random_walk_std ...
        * sqrt(dt);

    driving_noise_covariance = diag( ...
        [config.accelerometer_noise_std_x^2, ...
         config.accelerometer_noise_std_y^2, ...
         config.gyroscope_noise_std^2, ...
         accelerometer_bias_increment_std_x^2, ...
         accelerometer_bias_increment_std_y^2, ...
         gyroscope_bias_increment_std^2]);

    process_noise_covariance = ...
        config.process_noise_scale ...
        * noise_mapping ...
        * driving_noise_covariance ...
        * noise_mapping';

    predicted_covariance = ...
        state_transition_jacobian ...
        * current_covariance ...
        * state_transition_jacobian' ...
        + process_noise_covariance;

    predicted_covariance = ...
        0.5 ...
        * (predicted_covariance ...
        + predicted_covariance');
end


function [measurement, measurement_covariance] = ...
    create_quantum_bias_measurement( ...
        imu, ...
        quantum, ...
        sample_index, ...
        measurement_time, ...
        config)
%CREATE_QUANTUM_BIAS_MEASUREMENT Form the MEMS-bias observation.

    measurement = ...
        [imu.acceleration_x_measured(sample_index) ...
         - quantum.acceleration_x_measured(sample_index) ...
         + config.quantum.nominal_accelerometer_bias_x; ...
         ...
         imu.acceleration_y_measured(sample_index) ...
         - quantum.acceleration_y_measured(sample_index) ...
         + config.quantum.nominal_accelerometer_bias_y; ...
         ...
         imu.yaw_rate_measured(sample_index) ...
         - quantum.yaw_rate_measured(sample_index) ...
         + config.quantum.nominal_gyroscope_bias];

    elapsed_time = ...
        max(measurement_time, 0);

    variance_acceleration_x = ...
        config.quantum.mems_accelerometer_noise_std_x^2 ...
        + config.quantum.quantum_accelerometer_noise_std_x^2 ...
        + config.quantum.accelerometer_bias_calibration_std_x^2 ...
        + config.quantum.quantum_accelerometer_bias_rw_std_x^2 ...
        * elapsed_time;

    variance_acceleration_y = ...
        config.quantum.mems_accelerometer_noise_std_y^2 ...
        + config.quantum.quantum_accelerometer_noise_std_y^2 ...
        + config.quantum.accelerometer_bias_calibration_std_y^2 ...
        + config.quantum.quantum_accelerometer_bias_rw_std_y^2 ...
        * elapsed_time;

    variance_gyroscope = ...
        config.quantum.mems_gyroscope_noise_std^2 ...
        + config.quantum.quantum_gyroscope_noise_std^2 ...
        + config.quantum.gyroscope_bias_calibration_std^2 ...
        + config.quantum.quantum_gyroscope_bias_rw_std^2 ...
        * elapsed_time;

    measurement_covariance = ...
        config.quantum.measurement_covariance_scale ...
        * diag( ...
            [variance_acceleration_x, ...
             variance_acceleration_y, ...
             variance_gyroscope]);
end


function [corrected_state, ...
          corrected_covariance, ...
          innovation, ...
          innovation_covariance, ...
          normalized_innovation_squared] = ...
    apply_linear_measurement_update( ...
        predicted_state, ...
        predicted_covariance, ...
        measurement, ...
        measurement_matrix, ...
        measurement_covariance, ...
        use_joseph_form)
%APPLY_LINEAR_MEASUREMENT_UPDATE Perform a linear Kalman correction.

    innovation = ...
        measurement ...
        - measurement_matrix * predicted_state;

    innovation_covariance = ...
        measurement_matrix ...
        * predicted_covariance ...
        * measurement_matrix' ...
        + measurement_covariance;

    kalman_gain = ...
        (predicted_covariance ...
        * measurement_matrix') ...
        / innovation_covariance;

    corrected_state = ...
        predicted_state ...
        + kalman_gain * innovation;

    identity_matrix = ...
        eye(size(predicted_covariance));

    if use_joseph_form

        correction_matrix = ...
            identity_matrix ...
            - kalman_gain * measurement_matrix;

        corrected_covariance = ...
            correction_matrix ...
            * predicted_covariance ...
            * correction_matrix' ...
            + kalman_gain ...
            * measurement_covariance ...
            * kalman_gain';

    else

        corrected_covariance = ...
            (identity_matrix ...
            - kalman_gain * measurement_matrix) ...
            * predicted_covariance;
    end

    corrected_covariance = ...
        0.5 ...
        * (corrected_covariance ...
        + corrected_covariance');

    normalized_innovation_squared = ...
        innovation' ...
        * (innovation_covariance \ innovation);
end