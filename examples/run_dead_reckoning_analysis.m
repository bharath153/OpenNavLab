clear;
clc;
close all;

%% Identify project folders

current_script = mfilename('fullpath');
examples_folder = fileparts(current_script);
project_root = fileparts(examples_folder);

trajectory_source_folder = ...
    fullfile(project_root, 'src', 'trajectory');

sensor_source_folder = ...
    fullfile(project_root, 'src', 'sensors');

navigation_source_folder = ...
    fullfile(project_root, 'src', 'navigation');

config_folder = ...
    fullfile(project_root, 'config');

results_folder = ...
    fullfile(project_root, 'results');

figure_folder = ...
    fullfile(results_folder, 'figures');

data_folder = ...
    fullfile(results_folder, 'data');

%% Add source folders to MATLAB path

addpath(trajectory_source_folder);
addpath(sensor_source_folder);
addpath(navigation_source_folder);
addpath(config_folder);

%% Create output folders

if ~exist(results_folder, 'dir')
    mkdir(results_folder);
end

if ~exist(figure_folder, 'dir')
    mkdir(figure_folder);
end

if ~exist(data_folder, 'dir')
    mkdir(data_folder);
end

%% Simulation configuration

dt = 0.01;
simulation_time = 120;

%% Generate ground truth

truth = generate_truth_trajectory( ...
    dt, ...
    simulation_time);

%% Generate virtual IMU

imu_config = create_imu_config();

imu = simulate_imu( ...
    truth, ...
    imu_config);

%% Define navigation initial conditions

initial_state.position_x = truth.position_x(1);
initial_state.position_y = truth.position_y(1);

initial_state.velocity_x = truth.velocity_x(1);
initial_state.velocity_y = truth.velocity_y(1);

initial_state.heading = truth.heading(1);

%% Case 1: Ideal IMU dead reckoning

dead_reckoning_ideal = propagate_dead_reckoning( ...
    truth.time, ...
    truth.acceleration_body_x, ...
    truth.acceleration_body_y, ...
    truth.yaw_rate, ...
    initial_state);

%% Case 2: Noise-only dead reckoning
%
% The exact simulated bias is subtracted.
% This is a diagnostic case, not a realistic estimator.

acceleration_noise_only_x = ...
    imu.acceleration_x_measured ...
    - imu.accelerometer_bias_x;

acceleration_noise_only_y = ...
    imu.acceleration_y_measured ...
    - imu.accelerometer_bias_y;

yaw_rate_noise_only = ...
    imu.yaw_rate_measured ...
    - imu.gyroscope_bias;

dead_reckoning_noise_only = propagate_dead_reckoning( ...
    truth.time, ...
    acceleration_noise_only_x, ...
    acceleration_noise_only_y, ...
    yaw_rate_noise_only, ...
    initial_state);

%% Case 3: Complete virtual IMU dead reckoning

dead_reckoning_measured = propagate_dead_reckoning( ...
    truth.time, ...
    imu.acceleration_x_measured, ...
    imu.acceleration_y_measured, ...
    imu.yaw_rate_measured, ...
    initial_state);

%% Calculate position errors

position_error_ideal = hypot( ...
    dead_reckoning_ideal.position_x - truth.position_x, ...
    dead_reckoning_ideal.position_y - truth.position_y);

position_error_noise_only = hypot( ...
    dead_reckoning_noise_only.position_x - truth.position_x, ...
    dead_reckoning_noise_only.position_y - truth.position_y);

position_error_measured = hypot( ...
    dead_reckoning_measured.position_x - truth.position_x, ...
    dead_reckoning_measured.position_y - truth.position_y);

%% Calculate velocity errors

velocity_error_ideal = hypot( ...
    dead_reckoning_ideal.velocity_x - truth.velocity_x, ...
    dead_reckoning_ideal.velocity_y - truth.velocity_y);

velocity_error_noise_only = hypot( ...
    dead_reckoning_noise_only.velocity_x - truth.velocity_x, ...
    dead_reckoning_noise_only.velocity_y - truth.velocity_y);

velocity_error_measured = hypot( ...
    dead_reckoning_measured.velocity_x - truth.velocity_x, ...
    dead_reckoning_measured.velocity_y - truth.velocity_y);

%% Calculate wrapped heading errors

heading_error_ideal = atan2( ...
    sin(dead_reckoning_ideal.heading - truth.heading), ...
    cos(dead_reckoning_ideal.heading - truth.heading));

heading_error_noise_only = atan2( ...
    sin(dead_reckoning_noise_only.heading - truth.heading), ...
    cos(dead_reckoning_noise_only.heading - truth.heading));

heading_error_measured = atan2( ...
    sin(dead_reckoning_measured.heading - truth.heading), ...
    cos(dead_reckoning_measured.heading - truth.heading));

%% Calculate summary metrics

position_rmse_ideal = ...
    sqrt(mean(position_error_ideal.^2));

position_rmse_noise_only = ...
    sqrt(mean(position_error_noise_only.^2));

position_rmse_measured = ...
    sqrt(mean(position_error_measured.^2));

velocity_rmse_ideal = ...
    sqrt(mean(velocity_error_ideal.^2));

velocity_rmse_noise_only = ...
    sqrt(mean(velocity_error_noise_only.^2));

velocity_rmse_measured = ...
    sqrt(mean(velocity_error_measured.^2));

heading_rmse_ideal = ...
    sqrt(mean(rad2deg(heading_error_ideal).^2));

heading_rmse_noise_only = ...
    sqrt(mean(rad2deg(heading_error_noise_only).^2));

heading_rmse_measured = ...
    sqrt(mean(rad2deg(heading_error_measured).^2));

%% Display results

fprintf('\n');
fprintf('================================================\n');
fprintf('OpenNavLab Phase 3: IMU Dead Reckoning\n');
fprintf('================================================\n');

fprintf('\nIdeal IMU:\n');
fprintf('  Final position error: %.4f m\n', ...
    position_error_ideal(end));
fprintf('  Position RMSE:        %.4f m\n', ...
    position_rmse_ideal);
fprintf('  Final velocity error: %.4f m/s\n', ...
    velocity_error_ideal(end));
fprintf('  Heading RMSE:         %.6f deg\n', ...
    heading_rmse_ideal);

fprintf('\nNoise-only IMU:\n');
fprintf('  Final position error: %.4f m\n', ...
    position_error_noise_only(end));
fprintf('  Position RMSE:        %.4f m\n', ...
    position_rmse_noise_only);
fprintf('  Final velocity error: %.4f m/s\n', ...
    velocity_error_noise_only(end));
fprintf('  Final heading error:  %.4f deg\n', ...
    rad2deg(heading_error_noise_only(end)));
fprintf('  Heading RMSE:         %.4f deg\n', ...
    heading_rmse_noise_only);

fprintf('\nComplete virtual IMU:\n');
fprintf('  Final position error: %.4f m\n', ...
    position_error_measured(end));
fprintf('  Maximum position error: %.4f m\n', ...
    max(position_error_measured));
fprintf('  Position RMSE:        %.4f m\n', ...
    position_rmse_measured);
fprintf('  Final velocity error: %.4f m/s\n', ...
    velocity_error_measured(end));
fprintf('  Velocity RMSE:        %.4f m/s\n', ...
    velocity_rmse_measured);
fprintf('  Final heading error:  %.4f deg\n', ...
    rad2deg(heading_error_measured(end)));
fprintf('  Heading RMSE:         %.4f deg\n', ...
    heading_rmse_measured);

%% Automatic validation

assert( ...
    all(isfinite(dead_reckoning_ideal.position_x)), ...
    'Ideal dead reckoning contains invalid position values.');

assert( ...
    all(isfinite(dead_reckoning_noise_only.position_x)), ...
    'Noise-only dead reckoning contains invalid position values.');

assert( ...
    all(isfinite(dead_reckoning_measured.position_x)), ...
    'Measured dead reckoning contains invalid position values.');

assert( ...
    all(isfinite(dead_reckoning_measured.heading)), ...
    'Measured dead reckoning contains invalid heading values.');

assert( ...
    max(position_error_ideal) < 1.0, ...
    ['Ideal dead reckoning error is unexpectedly large. ' ...
     'Check the propagation equations.']);

assert( ...
    max(abs(rad2deg(heading_error_ideal))) < 1e-8, ...
    'Ideal heading propagation is inconsistent.');

assert( ...
    position_error_measured(end) > position_error_ideal(end), ...
    'The noisy IMU did not produce the expected additional drift.');

fprintf('\nAll Phase 3 validation checks passed successfully.\n');

