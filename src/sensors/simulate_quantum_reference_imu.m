function quantum = simulate_quantum_reference_imu( ...
    truth, ...
    config)
%SIMULATE_QUANTUM_REFERENCE_IMU Simulate a cold-atom inertial reference.
%
% Inputs:
%   truth  - Ground-truth trajectory structure.
%   config - Quantum sensor configuration.
%
% Output:
%   quantum - Quantum acceleration, yaw-rate, bias and phase data.
%
% Navigation-level measurement models:
%
%   z_ax = a_x_true + b_ax + n_ax
%   z_ay = a_y_true + b_ay + n_ay
%   z_g  = omega_true + b_g + n_g
%
% Bias evolution:
%
%   b(k+1) = b(k) + sigma_rw * sqrt(dt) * w(k)
%
% Equivalent atom-interferometer acceleration phase:
%
%   phi = k_eff * a * T^2
%
% The reported phase is unwrapped. The classical sensor is assumed to
% provide sufficient dynamic-range information to resolve fringe order.

    %% Validate truth fields

    required_truth_fields = { ...
        'time', ...
        'dt', ...
        'acceleration_body_x', ...
        'acceleration_body_y', ...
        'yaw_rate'};

    for field_index = 1:numel(required_truth_fields)

        current_field = required_truth_fields{field_index};

        if ~isfield(truth, current_field)

            error( ...
                'Truth structure is missing the field "%s".', ...
                current_field);
        end
    end

    %% Extract and format inputs

    time = truth.time(:);
    dt = truth.dt;

    acceleration_true_x = ...
        truth.acceleration_body_x(:);

    acceleration_true_y = ...
        truth.acceleration_body_y(:);

    yaw_rate_true = ...
        truth.yaw_rate(:);

    number_of_samples = numel(time);

    if number_of_samples < 2

        error( ...
            'At least two simulation samples are required.');
    end

    if numel(acceleration_true_x) ~= number_of_samples || ...
            numel(acceleration_true_y) ~= number_of_samples || ...
            numel(yaw_rate_true) ~= number_of_samples

        error( ...
            'Ground-truth sensor vectors must match the time vector.');
    end

    %% Validate configuration

    validateattributes( ...
        config.update_frequency, ...
        {'numeric'}, ...
        {'scalar', 'real', 'finite', 'positive'});

    validateattributes( ...
        config.accelerometer.noise_std_x, ...
        {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'});

    validateattributes( ...
        config.accelerometer.noise_std_y, ...
        {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'});

    validateattributes( ...
        config.gyroscope.noise_std, ...
        {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'});

    %% Calculate sensor update interval

    sensor_period = ...
        1 / config.update_frequency;

    samples_per_update_exact = ...
        sensor_period / dt;

    samples_per_update = ...
        round(samples_per_update_exact);

    if abs( ...
            samples_per_update_exact ...
            - samples_per_update) > 1e-9

        error( ...
            ['Quantum sensor update frequency is incompatible ' ...
             'with the simulation time step.']);
    end

    if samples_per_update < 1

        error( ...
            'Quantum sensor rate cannot exceed the simulation rate.');
    end

    %% Scheduled measurement mask

    scheduled_update_mask = ...
        false(number_of_samples, 1);

    scheduled_indices = ...
        1:samples_per_update:number_of_samples;

    scheduled_update_mask(scheduled_indices) = true;

    %% Outage mask

    outage_mask = ...
        false(number_of_samples, 1);

    if isfield(config, 'outage_windows') && ...
            ~isempty(config.outage_windows)

        outage_windows = config.outage_windows;

        if size(outage_windows, 2) ~= 2

            error( ...
                ['Each quantum-sensor outage must contain a ' ...
                 'start and end time.']);
        end

        for outage_index = 1:size(outage_windows, 1)

            outage_start = ...
                outage_windows(outage_index, 1);

            outage_end = ...
                outage_windows(outage_index, 2);

            if outage_end <= outage_start

                error( ...
                    'Quantum-sensor outage end must exceed its start.');
            end

            outage_mask = outage_mask | ...
                (time >= outage_start ...
                & time < outage_end);
        end
    end

    available_measurement_mask = ...
        scheduled_update_mask & ~outage_mask;

    valid_indices = ...
        find(available_measurement_mask);

    number_of_measurements = ...
        numel(valid_indices);

    %% Set random-number generator

    rng(config.random_seed, 'twister');

    %% Generate continuous bias evolution

    accelerometer_bias_x = ...
        zeros(number_of_samples, 1);

    accelerometer_bias_y = ...
        zeros(number_of_samples, 1);

    gyroscope_bias = ...
        zeros(number_of_samples, 1);

    accelerometer_bias_x(1) = ...
        config.accelerometer.initial_bias_x;

    accelerometer_bias_y(1) = ...
        config.accelerometer.initial_bias_y;

    gyroscope_bias(1) = ...
        config.gyroscope.initial_bias;

    accelerometer_bias_increment_std_x = ...
        config.accelerometer.bias_random_walk_std_x ...
        * sqrt(dt);

    accelerometer_bias_increment_std_y = ...
        config.accelerometer.bias_random_walk_std_y ...
        * sqrt(dt);

    gyroscope_bias_increment_std = ...
        config.gyroscope.bias_random_walk_std ...
        * sqrt(dt);

    accelerometer_bias_increment_x = ...
        accelerometer_bias_increment_std_x ...
        * randn(number_of_samples - 1, 1);

    accelerometer_bias_increment_y = ...
        accelerometer_bias_increment_std_y ...
        * randn(number_of_samples - 1, 1);

    gyroscope_bias_increment = ...
        gyroscope_bias_increment_std ...
        * randn(number_of_samples - 1, 1);

    accelerometer_bias_x(2:end) = ...
        accelerometer_bias_x(1) ...
        + cumsum(accelerometer_bias_increment_x);

    accelerometer_bias_y(2:end) = ...
        accelerometer_bias_y(1) ...
        + cumsum(accelerometer_bias_increment_y);

    gyroscope_bias(2:end) = ...
        gyroscope_bias(1) ...
        + cumsum(gyroscope_bias_increment);

    %% Preallocate measurement vectors

    acceleration_x_measured = ...
        nan(number_of_samples, 1);

    acceleration_y_measured = ...
        nan(number_of_samples, 1);

    yaw_rate_measured = ...
        nan(number_of_samples, 1);

    acceleration_noise_x = ...
        nan(number_of_samples, 1);

    acceleration_noise_y = ...
        nan(number_of_samples, 1);

    gyroscope_noise = ...
        nan(number_of_samples, 1);

    %% Generate white measurement noise

    valid_acceleration_noise_x = ...
        config.accelerometer.noise_std_x ...
        * randn(number_of_measurements, 1);

    valid_acceleration_noise_y = ...
        config.accelerometer.noise_std_y ...
        * randn(number_of_measurements, 1);

    valid_gyroscope_noise = ...
        config.gyroscope.noise_std ...
        * randn(number_of_measurements, 1);

    acceleration_noise_x(valid_indices) = ...
        valid_acceleration_noise_x;

    acceleration_noise_y(valid_indices) = ...
        valid_acceleration_noise_y;

    gyroscope_noise(valid_indices) = ...
        valid_gyroscope_noise;

    %% Generate quantum inertial measurements

    acceleration_x_measured(valid_indices) = ...
        acceleration_true_x(valid_indices) ...
        + accelerometer_bias_x(valid_indices) ...
        + valid_acceleration_noise_x;

    acceleration_y_measured(valid_indices) = ...
        acceleration_true_y(valid_indices) ...
        + accelerometer_bias_y(valid_indices) ...
        + valid_acceleration_noise_y;

    yaw_rate_measured(valid_indices) = ...
        yaw_rate_true(valid_indices) ...
        + gyroscope_bias(valid_indices) ...
        + valid_gyroscope_noise;

    %% Measurement errors

    acceleration_error_x = ...
        acceleration_x_measured ...
        - acceleration_true_x;

    acceleration_error_y = ...
        acceleration_y_measured ...
        - acceleration_true_y;

    yaw_rate_error = ...
        yaw_rate_measured ...
        - yaw_rate_true;

    %% Equivalent atom-interferometer acceleration phase

    phase_scale_factor = ...
        config.atom.acceleration_phase_scale_factor;

    acceleration_phase_true_x = ...
        nan(number_of_samples, 1);

    acceleration_phase_true_y = ...
        nan(number_of_samples, 1);

    acceleration_phase_measured_x = ...
        nan(number_of_samples, 1);

    acceleration_phase_measured_y = ...
        nan(number_of_samples, 1);

    acceleration_phase_error_x = ...
        nan(number_of_samples, 1);

    acceleration_phase_error_y = ...
        nan(number_of_samples, 1);

    acceleration_phase_true_x(valid_indices) = ...
        phase_scale_factor ...
        * acceleration_true_x(valid_indices);

    acceleration_phase_true_y(valid_indices) = ...
        phase_scale_factor ...
        * acceleration_true_y(valid_indices);

    acceleration_phase_measured_x(valid_indices) = ...
        phase_scale_factor ...
        * acceleration_x_measured(valid_indices);

    acceleration_phase_measured_y(valid_indices) = ...
        phase_scale_factor ...
        * acceleration_y_measured(valid_indices);

    acceleration_phase_error_x(valid_indices) = ...
        acceleration_phase_measured_x(valid_indices) ...
        - acceleration_phase_true_x(valid_indices);

    acceleration_phase_error_y(valid_indices) = ...
        acceleration_phase_measured_y(valid_indices) ...
        - acceleration_phase_true_y(valid_indices);

    %% Store outputs

    quantum.time = time;
    quantum.dt = dt;

    quantum.update_frequency = ...
        config.update_frequency;

    quantum.update_period = ...
        sensor_period;

    quantum.samples_per_update = ...
        samples_per_update;

    quantum.acceleration_x_measured = ...
        acceleration_x_measured;

    quantum.acceleration_y_measured = ...
        acceleration_y_measured;

    quantum.yaw_rate_measured = ...
        yaw_rate_measured;

    quantum.accelerometer_bias_x = ...
        accelerometer_bias_x;

    quantum.accelerometer_bias_y = ...
        accelerometer_bias_y;

    quantum.gyroscope_bias = ...
        gyroscope_bias;

    quantum.acceleration_noise_x = ...
        acceleration_noise_x;

    quantum.acceleration_noise_y = ...
        acceleration_noise_y;

    quantum.gyroscope_noise = ...
        gyroscope_noise;

    quantum.acceleration_error_x = ...
        acceleration_error_x;

    quantum.acceleration_error_y = ...
        acceleration_error_y;

    quantum.yaw_rate_error = ...
        yaw_rate_error;

    quantum.acceleration_phase_true_x = ...
        acceleration_phase_true_x;

    quantum.acceleration_phase_true_y = ...
        acceleration_phase_true_y;

    quantum.acceleration_phase_measured_x = ...
        acceleration_phase_measured_x;

    quantum.acceleration_phase_measured_y = ...
        acceleration_phase_measured_y;

    quantum.acceleration_phase_error_x = ...
        acceleration_phase_error_x;

    quantum.acceleration_phase_error_y = ...
        acceleration_phase_error_y;

    quantum.scheduled_update_mask = ...
        scheduled_update_mask;

    quantum.outage_mask = ...
        outage_mask;

    quantum.available_measurement_mask = ...
        available_measurement_mask;

    quantum.valid_measurement_indices = ...
        valid_indices;

    quantum.number_of_scheduled_updates = ...
        nnz(scheduled_update_mask);

    quantum.number_of_available_measurements = ...
        number_of_measurements;

    quantum.number_of_suppressed_measurements = ...
        nnz(scheduled_update_mask & outage_mask);

    quantum.config = config;
end