clear;
clc;
close all;

%% Identify project folders

current_script = mfilename('fullpath');
examples_folder = fileparts(current_script);
project_root = fileparts(examples_folder);

trajectory_source_folder = ...
    fullfile(project_root, 'src', 'trajectory');

results_folder = ...
    fullfile(project_root, 'results');

figure_folder = ...
    fullfile(results_folder, 'figures');

data_folder = ...
    fullfile(results_folder, 'data');

%% Add source code to MATLAB path

addpath(trajectory_source_folder);

%% Create result folders if they do not exist

if ~exist(results_folder, 'dir')
    mkdir(results_folder);
end

if ~exist(figure_folder, 'dir')
    mkdir(figure_folder);
end

if ~exist(data_folder, 'dir')
    mkdir(data_folder);
end

%% Simulation configuration

dt = 0.01;
simulation_time = 120;

%% Generate the ground-truth trajectory

truth = generate_truth_trajectory( ...
    dt, ...
    simulation_time);

%% Display simulation results

fprintf('\n');
fprintf('============================================\n');
fprintf('OpenNavLab Phase 1: Ground-Truth Simulation\n');
fprintf('============================================\n');

fprintf('Simulation duration: %.2f s\n', ...
    truth.time(end));

fprintf('Time step: %.4f s\n', ...
    truth.dt);

fprintf('Number of samples: %d\n', ...
    numel(truth.time));

fprintf('Final X position: %.2f m\n', ...
    truth.position_x(end));

fprintf('Final Y position: %.2f m\n', ...
    truth.position_y(end));

fprintf('Maximum speed: %.2f m/s\n', ...
    max(truth.speed));

fprintf('Final speed: %.6f m/s\n', ...
    truth.speed(end));

fprintf('Final heading: %.2f degrees\n', ...
    rad2deg(truth.heading(end)));

fprintf('Maximum positive lateral acceleration: %.4f m/s^2\n', ...
    max(truth.acceleration_body_y));

fprintf('Maximum negative lateral acceleration: %.4f m/s^2\n', ...
    min(truth.acceleration_body_y));

%% Phase 1 automatic validation

assert( ...
    all(isfinite(truth.position_x)), ...
    'Position X contains NaN or Inf values.');

assert( ...
    all(isfinite(truth.position_y)), ...
    'Position Y contains NaN or Inf values.');

assert( ...
    all(isfinite(truth.velocity_x)), ...
    'Velocity X contains NaN or Inf values.');

assert( ...
    all(isfinite(truth.velocity_y)), ...
    'Velocity Y contains NaN or Inf values.');

assert( ...
    all(isfinite(truth.heading)), ...
    'Heading contains NaN or Inf values.');

assert( ...
    all(truth.speed >= 0), ...
    'The calculated speed contains negative values.');

assert( ...
    abs(max(truth.speed) - 10) < 1e-6, ...
    'Maximum speed is not equal to 10 m/s.');

assert( ...
    truth.speed(end) < 1e-6, ...
    'The vehicle did not stop at the end of the simulation.');

expected_final_heading_degrees = -15;

assert( ...
    abs( ...
        rad2deg(truth.heading(end)) ...
        - expected_final_heading_degrees) < 1e-6, ...
    'Final heading is not equal to -15 degrees.');

expected_left_turn_acceleration = ...
    10 * deg2rad(4);

expected_right_turn_acceleration = ...
    10 * deg2rad(-5);

assert( ...
    abs( ...
        max(truth.acceleration_body_y) ...
        - expected_left_turn_acceleration) < 1e-6, ...
    'Left-turn lateral acceleration is incorrect.');

assert( ...
    abs( ...
        min(truth.acceleration_body_y) ...
        - expected_right_turn_acceleration) < 1e-6, ...
    'Right-turn lateral acceleration is incorrect.');

fprintf('\nAll Phase 1 validation checks passed successfully.\n');

%% Figure 1: Two-dimensional trajectory

figure_trajectory = figure( ...
    'Name', ...
    'Ground-Truth Vehicle Trajectory');

plot( ...
    truth.position_x, ...
    truth.position_y, ...
    'LineWidth', ...
    1.5);

hold on;

plot( ...
    truth.position_x(1), ...
    truth.position_y(1), ...
    'o', ...
    'MarkerSize', ...
    8, ...
    'LineWidth', ...
    1.5);

plot( ...
    truth.position_x(end), ...
    truth.position_y(end), ...
    'x', ...
    'MarkerSize', ...
    10, ...
    'LineWidth', ...
    1.5);

axis equal;
grid on;

xlabel('Global X position [m]');
ylabel('Global Y position [m]');
title('Ground-Truth Vehicle Trajectory');

legend( ...
    'Trajectory', ...
    'Start', ...
    'End', ...
    'Location', ...
    'best');

%% Figure 2: Speed

figure_speed = figure( ...
    'Name', ...
    'Ground-Truth Speed');

