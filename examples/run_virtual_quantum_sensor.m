clc;
close all;

%% Identify project folders

current_script = mfilename('fullpath');
examples_folder = fileparts(current_script);
project_root = fileparts(examples_folder);

trajectory_source_folder = ...
    fullfile(project_root, 'src', 'trajectory');

sensor_source_folder = ...
    fullfile(project_root, 'src', 'sensors');

config_folder = ...
    fullfile(project_root, 'config');

results_folder = ...
    fullfile(project_root, 'results');

figure_folder = ...
    fullfile(results_folder, 'figures');

data_folder = ...
    fullfile(results_folder, 'data');

%% Add source folders

addpath(trajectory_source_folder);
addpath(sensor_source_folder);
addpath(config_folder);

%% Create output folders

if ~exist(results_folder, 'dir')
    mkdir(results_folder);
end

if ~exist(figure_folder, 'dir')
    mkdir(figure_folder);
end

if ~exist(data_folder, 'dir')
    mkdir(data_folder);
end

%% Generate ground truth

dt = 0.01;
simulation_time = 120;

truth = generate_truth_trajectory( ...
    dt, ...
    simulation_time);

%% Configure and simulate the quantum sensor

quantum_config = ...
    create_quantum_sensor_config();

quantum = simulate_quantum_reference_imu( ...
    truth, ...
    quantum_config);

%% Extract valid measurements

valid_mask = ...
    quantum.available_measurement_mask;

valid_time = ...
    quantum.time(valid_mask);

valid_acceleration_error_x = ...
    quantum.acceleration_error_x(valid_mask);

valid_acceleration_error_y = ...
    quantum.acceleration_error_y(valid_mask);

valid_yaw_rate_error = ...
    quantum.yaw_rate_error(valid_mask);

valid_acceleration_noise_x = ...
    quantum.acceleration_noise_x(valid_mask);

valid_acceleration_noise_y = ...
    quantum.acceleration_noise_y(valid_mask);

valid_gyroscope_noise = ...
    quantum.gyroscope_noise(valid_mask);

%% Calculate measurement statistics

acceleration_x_error_mean = ...
    mean(valid_acceleration_error_x);

acceleration_y_error_mean = ...
    mean(valid_acceleration_error_y);

yaw_rate_error_mean = ...
    mean(valid_yaw_rate_error);

acceleration_x_noise_std = ...
    std(valid_acceleration_noise_x);

acceleration_y_noise_std = ...
    std(valid_acceleration_noise_y);

gyroscope_noise_std = ...
    std(valid_gyroscope_noise);

acceleration_x_error_rmse = ...
    sqrt(mean(valid_acceleration_error_x.^2));

acceleration_y_error_rmse = ...
    sqrt(mean(valid_acceleration_error_y.^2));

yaw_rate_error_rmse = ...
    sqrt(mean(valid_yaw_rate_error.^2));

