%% Automatic validation

number_of_samples = ...
    numel(truth.time);

assert( ...
    numel(quantum.acceleration_x_measured) ...
    == number_of_samples, ...
    'Quantum accelerometer X length is incorrect.');

assert( ...
    numel(quantum.acceleration_y_measured) ...
    == number_of_samples, ...
    'Quantum accelerometer Y length is incorrect.');

assert( ...
    numel(quantum.yaw_rate_measured) ...
    == number_of_samples, ...
    'Quantum gyroscope length is incorrect.');

assert( ...
    quantum.samples_per_update == 100, ...
    'The quantum sensor should update every 100 samples.');

assert( ...
    quantum.number_of_scheduled_updates == 121, ...
    'The scheduled quantum update count is incorrect.');

assert( ...
    quantum.number_of_available_measurements == 121, ...
    'The available quantum measurement count is incorrect.');

assert( ...
    all(isfinite( ...
        quantum.acceleration_x_measured(valid_mask))), ...
    'Valid quantum acceleration X measurements contain NaN or Inf.');

assert( ...
    all(isfinite( ...
        quantum.acceleration_y_measured(valid_mask))), ...
    'Valid quantum acceleration Y measurements contain NaN or Inf.');

assert( ...
    all(isfinite( ...
        quantum.yaw_rate_measured(valid_mask))), ...
    'Valid quantum gyroscope measurements contain NaN or Inf.');

assert( ...
    all(isnan( ...
        quantum.acceleration_x_measured(~valid_mask))), ...
    'Unavailable acceleration X samples must be NaN.');

assert( ...
    all(isnan( ...
        quantum.acceleration_y_measured(~valid_mask))), ...
    'Unavailable acceleration Y samples must be NaN.');

assert( ...
    all(isnan( ...
        quantum.yaw_rate_measured(~valid_mask))), ...
    'Unavailable yaw-rate samples must be NaN.');

acceleration_x_measurement_residual = ...
    quantum.acceleration_x_measured(valid_mask) ...
    - truth.acceleration_body_x(valid_mask) ...
    - quantum.accelerometer_bias_x(valid_mask) ...
    - quantum.acceleration_noise_x(valid_mask);

acceleration_y_measurement_residual = ...
    quantum.acceleration_y_measured(valid_mask) ...
    - truth.acceleration_body_y(valid_mask) ...
    - quantum.accelerometer_bias_y(valid_mask) ...
    - quantum.acceleration_noise_y(valid_mask);

yaw_rate_measurement_residual = ...
    quantum.yaw_rate_measured(valid_mask) ...
    - truth.yaw_rate(valid_mask) ...
    - quantum.gyroscope_bias(valid_mask) ...
    - quantum.gyroscope_noise(valid_mask);

assert( ...
    max(abs(acceleration_x_measurement_residual)) < 1e-12, ...
    'Quantum accelerometer X equation is inconsistent.');

assert( ...
    max(abs(acceleration_y_measurement_residual)) < 1e-12, ...
    'Quantum accelerometer Y equation is inconsistent.');

assert( ...
    max(abs(yaw_rate_measurement_residual)) < 1e-12, ...
    'Quantum gyroscope equation is inconsistent.');

acceleration_x_noise_relative_error = ...
    abs( ...
        acceleration_x_noise_std ...
        - quantum_config.accelerometer.noise_std_x) ...
    / quantum_config.accelerometer.noise_std_x;

acceleration_y_noise_relative_error = ...
    abs( ...
        acceleration_y_noise_std ...
        - quantum_config.accelerometer.noise_std_y) ...
    / quantum_config.accelerometer.noise_std_y;

gyroscope_noise_relative_error = ...
    abs( ...
        gyroscope_noise_std ...
        - quantum_config.gyroscope.noise_std) ...
    / quantum_config.gyroscope.noise_std;

assert( ...
    acceleration_x_noise_relative_error < 0.35, ...
    'Quantum accelerometer X noise standard deviation is unexpected.');

assert( ...
    acceleration_y_noise_relative_error < 0.35, ...
    'Quantum accelerometer Y noise standard deviation is unexpected.');

assert( ...
    gyroscope_noise_relative_error < 0.35, ...
    'Quantum gyroscope noise standard deviation is unexpected.');

assert( ...
    all(isfinite( ...
        quantum.acceleration_phase_measured_x(valid_mask))), ...
    'Quantum phase X contains invalid values.');

assert( ...
    all(isfinite( ...
        quantum.acceleration_phase_measured_y(valid_mask))), ...
    'Quantum phase Y contains invalid values.');

fprintf('\nAll Phase 7A validation checks passed successfully.\n');

