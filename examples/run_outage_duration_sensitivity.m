function gps = apply_outage_to_gps( ...
    gps_full, ...
    time, ...
    outage_start_time, ...
    outage_duration)
%APPLY_OUTAGE_TO_GPS Remove measurements inside a requested GPS outage.
%
% The complete GPS realization is created before this function is called.
% Consequently, every outage-duration case uses identical GPS noise at all
% measurements that remain available.

    gps = gps_full;
    time = time(:);

    outage_mask = ...
        false(size(time));

    if outage_duration > 0

        outage_end_time = ...
            outage_start_time ...
            + outage_duration;

        outage_mask = ...
            time >= outage_start_time ...
            & time < outage_end_time;

        gps.config.outage_windows = ...
            [outage_start_time, outage_end_time];

    else

        gps.config.outage_windows = [];
    end

    available_measurement_mask = ...
        gps.scheduled_update_mask ...
        & ~outage_mask;

    unavailable_measurement_mask = ...
        ~available_measurement_mask;

    fields_to_mask = { ...
        'position_x_measured', ...
        'position_y_measured', ...
        'position_noise_x', ...
        'position_noise_y', ...
        'position_error_x', ...
        'position_error_y', ...
        'horizontal_position_error'};

    for field_index = 1:numel(fields_to_mask)

        current_field = ...
            fields_to_mask{field_index};

        gps.(current_field)( ...
            unavailable_measurement_mask) = NaN;
    end

    gps.outage_mask = ...
        outage_mask;

    gps.available_measurement_mask = ...
        available_measurement_mask;

    gps.valid_measurement_indices = ...
        find(available_measurement_mask);

    gps.number_of_available_measurements = ...
        nnz(available_measurement_mask);

    gps.number_of_suppressed_measurements = ...
        nnz( ...
            gps.scheduled_update_mask ...
            & outage_mask);
end


function percentile_value = calculate_percentile( ...
    values, ...
    requested_percentile)
%CALCULATE_PERCENTILE Calculate a percentile without extra toolboxes.

    values = values(:);
    values = values(isfinite(values));

    if isempty(values)

        error( ...
            'Cannot calculate a percentile from an empty vector.');
    end

    if requested_percentile < 0 || ...
            requested_percentile > 100

        error( ...
            'The requested percentile must be between 0 and 100.');
    end

    sorted_values = sort(values);
    number_of_values = numel(sorted_values);

    if number_of_values == 1

        percentile_value = sorted_values(1);
        return;
    end

    fractional_index = ...
        1 ...
        + (number_of_values - 1) ...
        * requested_percentile ...
        / 100;

    lower_index = floor(fractional_index);
    upper_index = ceil(fractional_index);

    if lower_index == upper_index

        percentile_value = ...
            sorted_values(lower_index);

    else

        interpolation_fraction = ...
            fractional_index ...
            - lower_index;

        percentile_value = ...
            sorted_values(lower_index) ...
            + interpolation_fraction ...
            * ( ...
                sorted_values(upper_index) ...
                - sorted_values(lower_index));
    end
end