clear;
clc;
close all;

%% Identify project folders

current_script = mfilename('fullpath');
examples_folder = fileparts(current_script);
project_root = fileparts(examples_folder);

trajectory_source_folder = ...
    fullfile(project_root, 'src', 'trajectory');

sensor_source_folder = ...
    fullfile(project_root, 'src', 'sensors');

config_folder = ...
    fullfile(project_root, 'config');

results_folder = ...
    fullfile(project_root, 'results');

figure_folder = ...
    fullfile(results_folder, 'figures');

data_folder = ...
    fullfile(results_folder, 'data');

%% Add source folders to MATLAB path

addpath(trajectory_source_folder);
addpath(sensor_source_folder);
addpath(config_folder);

%% Create output folders if required

if ~exist(results_folder, 'dir')
    mkdir(results_folder);
end

if ~exist(figure_folder, 'dir')
    mkdir(figure_folder);
end

if ~exist(data_folder, 'dir')
    mkdir(data_folder);
end

%% Simulation configuration

dt = 0.01;
simulation_time = 120;

%% Generate ground truth

truth = generate_truth_trajectory( ...
    dt, ...
    simulation_time);

%% Create GPS configuration

gps_config = create_gps_config();

%% Generate virtual GPS measurements

gps = simulate_gps( ...
    truth, ...
    gps_config);

%% Extract valid GPS measurements

valid_mask = ...
    gps.available_measurement_mask;

valid_indices = ...
    gps.valid_measurement_indices;

valid_time = ...
    gps.time(valid_mask);

valid_error_x = ...
    gps.position_error_x(valid_mask);

valid_error_y = ...
    gps.position_error_y(valid_mask);

valid_horizontal_error = ...
    gps.horizontal_position_error(valid_mask);

%% Calculate GPS statistics

position_error_x_mean = ...
    mean(valid_error_x);

position_error_y_mean = ...
    mean(valid_error_y);

position_error_x_std = ...
    std(valid_error_x);

position_error_y_std = ...
    std(valid_error_y);

position_rmse_x = ...
    sqrt(mean(valid_error_x.^2));

position_rmse_y = ...
    sqrt(mean(valid_error_y.^2));

horizontal_position_rmse = ...
    sqrt(mean(valid_horizontal_error.^2));

mean_horizontal_position_error = ...
    mean(valid_horizontal_error);

maximum_horizontal_position_error = ...
    max(valid_horizontal_error);

%% Display results

fprintf('\n');
fprintf('============================================\n');
fprintf('OpenNavLab Phase 4: Virtual GPS Simulation\n');
fprintf('============================================\n');

fprintf('Simulation sampling frequency: %.2f Hz\n', ...
    1 / truth.dt);

fprintf('GPS update frequency: %.2f Hz\n', ...
    gps.update_frequency);

fprintf('GPS update period: %.2f s\n', ...
    gps.update_period);

fprintf('Samples per GPS update: %d\n', ...
    gps.samples_per_update);

fprintf('\nMeasurement availability:\n');

fprintf('  Scheduled GPS updates:     %d\n', ...
    gps.number_of_scheduled_updates);

fprintf('  Available GPS measurements: %d\n', ...
    gps.number_of_available_measurements);

fprintf('  Suppressed by outage:       %d\n', ...
    gps.number_of_suppressed_measurements);

fprintf('\nGPS X-position error:\n');

fprintf('  Mean: %.4f m\n', ...
    position_error_x_mean);

fprintf('  Standard deviation: %.4f m\n', ...
    position_error_x_std);

fprintf('  RMSE: %.4f m\n', ...
    position_rmse_x);

fprintf('\nGPS Y-position error:\n');

fprintf('  Mean: %.4f m\n', ...
    position_error_y_mean);

fprintf('  Standard deviation: %.4f m\n', ...
    position_error_y_std);

fprintf('  RMSE: %.4f m\n', ...
    position_rmse_y);

fprintf('\nHorizontal position error:\n');

fprintf('  Mean error: %.4f m\n', ...
    mean_horizontal_position_error);

fprintf('  Horizontal RMSE: %.4f m\n', ...
    horizontal_position_rmse);

fprintf('  Maximum error: %.4f m\n', ...
    maximum_horizontal_position_error);

%% Automatic Phase 4 validation

number_of_samples = numel(truth.time);

assert( ...
    numel(gps.position_x_measured) == number_of_samples, ...
    'GPS X-position vector length is incorrect.');

assert( ...
    numel(gps.position_y_measured) == number_of_samples, ...
    'GPS Y-position vector length is incorrect.');

assert( ...
    gps.samples_per_update == 100, ...
    'GPS should update every 100 simulation samples.');

assert( ...
    gps.number_of_scheduled_updates == 121, ...
    'The scheduled GPS update count is incorrect.');

assert( ...
    gps.number_of_suppressed_measurements == 20, ...
    'The GPS outage should suppress 20 scheduled measurements.');

assert( ...
    gps.number_of_available_measurements == 101, ...
    'The number of available GPS measurements is incorrect.');

assert( ...
    all(isfinite( ...
        gps.position_x_measured(valid_mask))), ...
    'Valid GPS X measurements contain NaN or Inf.');

assert( ...
    all(isfinite( ...
        gps.position_y_measured(valid_mask))), ...
    'Valid GPS Y measurements contain NaN or Inf.');

assert( ...
    all(isnan( ...
        gps.position_x_measured(~valid_mask))), ...
    'Unavailable GPS X samples must be NaN.');

assert( ...
    all(isnan( ...
        gps.position_y_measured(~valid_mask))), ...
    'Unavailable GPS Y samples must be NaN.');

assert( ...
    ~any(gps.available_measurement_mask & gps.outage_mask), ...
    'GPS measurements were generated during the outage.');

assert( ...
    all( ...
        gps.available_measurement_mask ...
        <= gps.scheduled_update_mask), ...
    'GPS measurements exist at unscheduled simulation samples.');

gps_x_model_residual = ...
    gps.position_x_measured(valid_mask) ...
    - truth.position_x(valid_mask) ...
    - gps.position_noise_x(valid_mask);

gps_y_model_residual = ...
    gps.position_y_measured(valid_mask) ...
    - truth.position_y(valid_mask) ...
    - gps.position_noise_y(valid_mask);

assert( ...
    max(abs(gps_x_model_residual)) < 1e-12, ...
    'GPS X measurement equation is inconsistent.');

assert( ...
    max(abs(gps_y_model_residual)) < 1e-12, ...
    'GPS Y measurement equation is inconsistent.');

gps_x_std_relative_error = ...
    abs( ...
        position_error_x_std ...
        - gps_config.position_noise_std_x) ...
    / gps_config.position_noise_std_x;

gps_y_std_relative_error = ...
    abs( ...
        position_error_y_std ...
        - gps_config.position_noise_std_y) ...
    / gps_config.position_noise_std_y;

assert( ...
    gps_x_std_relative_error < 0.30, ...
    'GPS X noise standard deviation is unexpected.');

assert( ...
    gps_y_std_relative_error < 0.30, ...
    'GPS Y noise standard deviation is unexpected.');

fprintf('\nAll Phase 4 validation checks passed successfully.\n');

