function ekf = run_ekf_navigation( ...
    imu, ...
    gps, ...
    initial_state, ...
    config)
%RUN_EKF_NAVIGATION Perform 2D GPS/IMU navigation using an EKF.
%
% State vector:
%
%   x = [px, py, vx, vy, psi, bax, bay, bg]'
%
% Inputs:
%   imu           - Virtual IMU data from simulate_imu.m
%   gps           - Virtual GPS data from simulate_gps.m
%   initial_state - Initial navigation state and bias estimates
%   config        - EKF configuration
%
% Output:
%   ekf           - Estimated states, covariance history,
%                   innovations and consistency statistics.
%
% The filter predicts at the IMU frequency and performs a GPS correction
% only when a valid GPS position measurement is available.

    %% State indices

    PX = config.index.position_x;
    PY = config.index.position_y;

    VX = config.index.velocity_x;
    VY = config.index.velocity_y;

    PSI = config.index.heading;

    BAX = config.index.accelerometer_bias_x;
    BAY = config.index.accelerometer_bias_y;

    BG = config.index.gyroscope_bias;

    number_of_states = config.number_of_states;

    %% Input validation

    time = imu.time(:);
    number_of_samples = numel(time);

    if number_of_samples < 2
        error('At least two IMU samples are required.');
    end

    if numel(gps.time) ~= number_of_samples
        error('GPS and IMU time vectors must have equal lengths.');
    end

    if max(abs(gps.time(:) - time)) > 1e-12
        error('GPS and IMU time vectors are inconsistent.');
    end

    imu_vectors = { ...
        imu.acceleration_x_measured, ...
        imu.acceleration_y_measured, ...
        imu.yaw_rate_measured};

    for vector_index = 1:numel(imu_vectors)

        if numel(imu_vectors{vector_index}) ~= number_of_samples
            error('An IMU measurement vector has an incorrect length.');
        end
    end

    required_initial_fields = { ...
        'position_x', ...
        'position_y', ...
        'velocity_x', ...
        'velocity_y', ...
        'heading', ...
        'accelerometer_bias_x', ...
        'accelerometer_bias_y', ...
        'gyroscope_bias'};

    for field_index = 1:numel(required_initial_fields)

        current_field = required_initial_fields{field_index};

        if ~isfield(initial_state, current_field)
            error( ...
                'Initial state is missing the field "%s".', ...
                current_field);
        end
    end

    %% Preallocate EKF outputs

    state_estimate = ...
        zeros(number_of_states, number_of_samples);

    covariance_history = ...
        zeros( ...
            number_of_states, ...
            number_of_states, ...
            number_of_samples);

    innovation = ...
        nan(2, number_of_samples);

    innovation_covariance_history = ...
        nan(2, 2, number_of_samples);

    normalized_innovation_squared = ...
        nan(number_of_samples, 1);

    gps_update_applied = ...
        false(number_of_samples, 1);

    %% Initial state estimate

    state_estimate(:, 1) = ...
        [initial_state.position_x; ...
         initial_state.position_y; ...
         initial_state.velocity_x; ...
         initial_state.velocity_y; ...
         initial_state.heading; ...
         initial_state.accelerometer_bias_x; ...
         initial_state.accelerometer_bias_y; ...
         initial_state.gyroscope_bias];

    covariance = config.initial_covariance;

    %% GPS measurement model

    measurement_matrix = zeros(2, number_of_states);

    measurement_matrix(1, PX) = 1;
    measurement_matrix(2, PY) = 1;

    gps_measurement_covariance = ...
        config.gps_measurement_covariance;

    %% Apply GPS correction at the initial sample

    if gps.available_measurement_mask(1)

        gps_measurement = ...
            [gps.position_x_measured(1); ...
             gps.position_y_measured(1)];

        [state_estimate(:, 1), ...
         covariance, ...
         innovation(:, 1), ...
         innovation_covariance_history(:, :, 1), ...
         normalized_innovation_squared(1)] = ...
            apply_gps_update( ...
                state_estimate(:, 1), ...
                covariance, ...
                gps_measurement, ...
                measurement_matrix, ...
                gps_measurement_covariance, ...
                config.use_joseph_covariance_update);

        gps_update_applied(1) = true;
    end

    covariance_history(:, :, 1) = covariance;

    %% EKF prediction and correction

    for k = 1:number_of_samples - 1

        dt = time(k + 1) - time(k);

        if dt <= 0
            error('The IMU time vector must be strictly increasing.');
        end

        current_state = state_estimate(:, k);

        position_x = current_state(PX);
        position_y = current_state(PY);

        velocity_x = current_state(VX);
        velocity_y = current_state(VY);

        heading = current_state(PSI);

        accelerometer_bias_x = current_state(BAX);
        accelerometer_bias_y = current_state(BAY);

        gyroscope_bias = current_state(BG);

        %% Bias-correct the IMU measurements

        acceleration_body_x = ...
            imu.acceleration_x_measured(k) ...
            - accelerometer_bias_x;

        acceleration_body_y = ...
            imu.acceleration_y_measured(k) ...
            - accelerometer_bias_y;

        corrected_yaw_rate = ...
            imu.yaw_rate_measured(k) ...
            - gyroscope_bias;

        %% Transform acceleration into the navigation frame

        cosine_heading = cos(heading);
        sine_heading = sin(heading);

        rotation_body_to_navigation = ...
            [cosine_heading, -sine_heading; ...
             sine_heading,  cosine_heading];

        acceleration_navigation = ...
            rotation_body_to_navigation ...
            * [acceleration_body_x; ...
               acceleration_body_y];

        acceleration_navigation_x = ...
            acceleration_navigation(1);

        acceleration_navigation_y = ...
            acceleration_navigation(2);

        %% Nonlinear state prediction

        predicted_state = current_state;

        predicted_state(PX) = ...
            position_x ...
            + velocity_x * dt ...
            + 0.5 * acceleration_navigation_x * dt^2;

        predicted_state(PY) = ...
            position_y ...
            + velocity_y * dt ...
            + 0.5 * acceleration_navigation_y * dt^2;

        predicted_state(VX) = ...
            velocity_x ...
            + acceleration_navigation_x * dt;

        predicted_state(VY) = ...
            velocity_y ...
            + acceleration_navigation_y * dt;

        predicted_heading = ...
            heading + corrected_yaw_rate * dt;

        predicted_state(PSI) = atan2( ...
            sin(predicted_heading), ...
            cos(predicted_heading));

        % Random-walk bias states have zero expected change.
        predicted_state(BAX) = accelerometer_bias_x;
        predicted_state(BAY) = accelerometer_bias_y;
        predicted_state(BG) = gyroscope_bias;

        %% State-transition Jacobian

        acceleration_x_heading_derivative = ...
            -sine_heading * acceleration_body_x ...
            -cosine_heading * acceleration_body_y;

        acceleration_y_heading_derivative = ...
             cosine_heading * acceleration_body_x ...
            -sine_heading * acceleration_body_y;

        state_transition_jacobian = ...
            eye(number_of_states);

        state_transition_jacobian(PX, VX) = dt;
        state_transition_jacobian(PY, VY) = dt;

        state_transition_jacobian(PX, PSI) = ...
            0.5 ...
            * acceleration_x_heading_derivative ...
            * dt^2;

        state_transition_jacobian(PY, PSI) = ...
            0.5 ...
            * acceleration_y_heading_derivative ...
            * dt^2;

        state_transition_jacobian(VX, PSI) = ...
            acceleration_x_heading_derivative * dt;

        state_transition_jacobian(VY, PSI) = ...
            acceleration_y_heading_derivative * dt;

        % Derivatives with respect to accelerometer bias.
        state_transition_jacobian(PX, BAX) = ...
            -0.5 * cosine_heading * dt^2;

        state_transition_jacobian(PX, BAY) = ...
             0.5 * sine_heading * dt^2;

        state_transition_jacobian(PY, BAX) = ...
            -0.5 * sine_heading * dt^2;

        state_transition_jacobian(PY, BAY) = ...
            -0.5 * cosine_heading * dt^2;

        state_transition_jacobian(VX, BAX) = ...
            -cosine_heading * dt;

        state_transition_jacobian(VX, BAY) = ...
             sine_heading * dt;

        state_transition_jacobian(VY, BAX) = ...
            -sine_heading * dt;

        state_transition_jacobian(VY, BAY) = ...
            -cosine_heading * dt;

        state_transition_jacobian(PSI, BG) = -dt;

        %% Process-noise mapping

        % Driving-noise vector:
        %
        % [accelerometer_noise_x
        %  accelerometer_noise_y
        %  gyroscope_noise
        %  accelerometer_bias_random_walk_x
        %  accelerometer_bias_random_walk_y
        %  gyroscope_bias_random_walk]

        noise_mapping = zeros(number_of_states, 6);

        noise_mapping( ...
            [PX, PY], ...
            [1, 2]) = ...
            0.5 ...
            * rotation_body_to_navigation ...
            * dt^2;

        noise_mapping( ...
            [VX, VY], ...
            [1, 2]) = ...
            rotation_body_to_navigation ...
            * dt;

        noise_mapping(PSI, 3) = dt;

        noise_mapping(BAX, 4) = 1;
        noise_mapping(BAY, 5) = 1;
        noise_mapping(BG, 6) = 1;

        accelerometer_bias_increment_std_x = ...
            config.accelerometer_bias_random_walk_std_x ...
            * sqrt(dt);

        accelerometer_bias_increment_std_y = ...
            config.accelerometer_bias_random_walk_std_y ...
            * sqrt(dt);

        gyroscope_bias_increment_std = ...
            config.gyroscope_bias_random_walk_std ...
            * sqrt(dt);

        driving_noise_covariance = diag( ...
            [config.accelerometer_noise_std_x^2, ...
             config.accelerometer_noise_std_y^2, ...
             config.gyroscope_noise_std^2, ...
             accelerometer_bias_increment_std_x^2, ...
             accelerometer_bias_increment_std_y^2, ...
             gyroscope_bias_increment_std^2]);

        process_noise_covariance = ...
            config.process_noise_scale ...
            * noise_mapping ...
            * driving_noise_covariance ...
            * noise_mapping';

        %% Covariance prediction

        predicted_covariance = ...
            state_transition_jacobian ...
            * covariance ...
            * state_transition_jacobian' ...
            + process_noise_covariance;

        predicted_covariance = ...
            0.5 ...
            * (predicted_covariance ...
            + predicted_covariance');

        %% GPS measurement correction

        if gps.available_measurement_mask(k + 1)

            gps_measurement = ...
                [gps.position_x_measured(k + 1); ...
                 gps.position_y_measured(k + 1)];

            [corrected_state, ...
             covariance, ...
             innovation(:, k + 1), ...
             innovation_covariance_history(:, :, k + 1), ...
             normalized_innovation_squared(k + 1)] = ...
                apply_gps_update( ...
                    predicted_state, ...
                    predicted_covariance, ...
                    gps_measurement, ...
                    measurement_matrix, ...
                    gps_measurement_covariance, ...
                    config.use_joseph_covariance_update);

            state_estimate(:, k + 1) = ...
                corrected_state;

            gps_update_applied(k + 1) = true;

        else

            state_estimate(:, k + 1) = ...
                predicted_state;

            covariance = ...
                predicted_covariance;
        end

        %% Wrap the corrected heading

        state_estimate(PSI, k + 1) = atan2( ...
            sin(state_estimate(PSI, k + 1)), ...
            cos(state_estimate(PSI, k + 1)));

        covariance = ...
            0.5 * (covariance + covariance');

        covariance_history(:, :, k + 1) = ...
            covariance;
    end

    %% Extract state standard deviations

    covariance_standard_deviation = ...
        zeros(number_of_states, number_of_samples);

    for k = 1:number_of_samples

        covariance_diagonal = ...
            diag(covariance_history(:, :, k));

        covariance_diagonal = ...
            max(covariance_diagonal, 0);

        covariance_standard_deviation(:, k) = ...
            sqrt(covariance_diagonal);
    end

    %% Store outputs

    ekf.time = time;
    ekf.state_estimate = state_estimate;

    ekf.position_x = state_estimate(PX, :)';
    ekf.position_y = state_estimate(PY, :)';

    ekf.velocity_x = state_estimate(VX, :)';
    ekf.velocity_y = state_estimate(VY, :)';

    ekf.speed = hypot( ...
        ekf.velocity_x, ...
        ekf.velocity_y);

    ekf.heading = state_estimate(PSI, :)';

    ekf.accelerometer_bias_x = ...
        state_estimate(BAX, :)';

    ekf.accelerometer_bias_y = ...
        state_estimate(BAY, :)';

    ekf.gyroscope_bias = ...
        state_estimate(BG, :)';

    ekf.covariance_history = ...
        covariance_history;

    ekf.covariance_standard_deviation = ...
        covariance_standard_deviation;

    ekf.innovation = innovation;

    ekf.innovation_covariance_history = ...
        innovation_covariance_history;

    ekf.normalized_innovation_squared = ...
        normalized_innovation_squared;

    ekf.gps_update_applied = ...
        gps_update_applied;

    ekf.number_of_gps_updates = ...
        nnz(gps_update_applied);

    ekf.config = config;
end


function [corrected_state, ...
          corrected_covariance, ...
          innovation, ...
          innovation_covariance, ...
          normalized_innovation_squared] = ...
    apply_gps_update( ...
        predicted_state, ...
        predicted_covariance, ...
        gps_measurement, ...
        measurement_matrix, ...
        measurement_covariance, ...
        use_joseph_form)
%APPLY_GPS_UPDATE Apply a two-dimensional GPS position correction.

    innovation = ...
        gps_measurement ...
        - measurement_matrix * predicted_state;

    innovation_covariance = ...
        measurement_matrix ...
        * predicted_covariance ...
        * measurement_matrix' ...
        + measurement_covariance;

    kalman_gain = ...
        (predicted_covariance ...
        * measurement_matrix') ...
        / innovation_covariance;

    corrected_state = ...
        predicted_state ...
        + kalman_gain * innovation;

    identity_matrix = ...
        eye(size(predicted_covariance));

    if use_joseph_form

        correction_matrix = ...
            identity_matrix ...
            - kalman_gain * measurement_matrix;

        corrected_covariance = ...
            correction_matrix ...
            * predicted_covariance ...
            * correction_matrix' ...
            + kalman_gain ...
            * measurement_covariance ...
            * kalman_gain';

    else

        corrected_covariance = ...
            (identity_matrix ...
            - kalman_gain * measurement_matrix) ...
            * predicted_covariance;
    end

    corrected_covariance = ...
        0.5 ...
        * (corrected_covariance ...
        + corrected_covariance');

    normalized_innovation_squared = ...
        innovation' ...
        * (innovation_covariance \ innovation);
end