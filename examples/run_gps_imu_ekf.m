clear;
clc;
close all;

%% Identify project folders

current_script = mfilename('fullpath');
examples_folder = fileparts(current_script);
project_root = fileparts(examples_folder);

trajectory_source_folder = ...
    fullfile(project_root, 'src', 'trajectory');

sensor_source_folder = ...
    fullfile(project_root, 'src', 'sensors');

navigation_source_folder = ...
    fullfile(project_root, 'src', 'navigation');

filter_source_folder = ...
    fullfile(project_root, 'src', 'filters');

config_folder = ...
    fullfile(project_root, 'config');

results_folder = ...
    fullfile(project_root, 'results');

figure_folder = ...
    fullfile(results_folder, 'figures');

data_folder = ...
    fullfile(results_folder, 'data');

%% Add source folders

addpath(trajectory_source_folder);
addpath(sensor_source_folder);
addpath(navigation_source_folder);
addpath(filter_source_folder);
addpath(config_folder);

%% Create result folders

if ~exist(results_folder, 'dir')
    mkdir(results_folder);
end

if ~exist(figure_folder, 'dir')
    mkdir(figure_folder);
end

if ~exist(data_folder, 'dir')
    mkdir(data_folder);
end

%% Simulation configuration

dt = 0.01;
simulation_time = 120;

%% Generate ground truth

truth = generate_truth_trajectory( ...
    dt, ...
    simulation_time);

%% Generate virtual IMU

imu_config = create_imu_config();

imu = simulate_imu( ...
    truth, ...
    imu_config);

%% Generate virtual GPS

gps_config = create_gps_config();

gps = simulate_gps( ...
    truth, ...
    gps_config);

%% IMU-only dead-reckoning baseline

dead_reckoning_initial_state.position_x = ...
    truth.position_x(1);

dead_reckoning_initial_state.position_y = ...
    truth.position_y(1);

dead_reckoning_initial_state.velocity_x = ...
    truth.velocity_x(1);

dead_reckoning_initial_state.velocity_y = ...
    truth.velocity_y(1);

dead_reckoning_initial_state.heading = ...
    truth.heading(1);

dead_reckoning = propagate_dead_reckoning( ...
    truth.time, ...
    imu.acceleration_x_measured, ...
    imu.acceleration_y_measured, ...
    imu.yaw_rate_measured, ...
    dead_reckoning_initial_state);

%% Configure the EKF

ekf_config = create_ekf_config( ...
    imu_config, ...
    gps_config);

%% EKF initial state

initial_state.position_x = truth.position_x(1);
initial_state.position_y = truth.position_y(1);

initial_state.velocity_x = truth.velocity_x(1);
initial_state.velocity_y = truth.velocity_y(1);

initial_state.heading = truth.heading(1);

% The EKF is not supplied with the true sensor biases.
initial_state.accelerometer_bias_x = 0;
initial_state.accelerometer_bias_y = 0;
initial_state.gyroscope_bias = 0;

%% Run the EKF

ekf = run_ekf_navigation( ...
    imu, ...
    gps, ...
    initial_state, ...
    ekf_config);

%% Calculate position errors

dead_reckoning_position_error = hypot( ...
    dead_reckoning.position_x - truth.position_x, ...
    dead_reckoning.position_y - truth.position_y);

ekf_position_error = hypot( ...
    ekf.position_x - truth.position_x, ...
    ekf.position_y - truth.position_y);

%% Calculate velocity errors

dead_reckoning_velocity_error = hypot( ...
    dead_reckoning.velocity_x - truth.velocity_x, ...
    dead_reckoning.velocity_y - truth.velocity_y);

ekf_velocity_error = hypot( ...
    ekf.velocity_x - truth.velocity_x, ...
    ekf.velocity_y - truth.velocity_y);

%% Calculate wrapped heading errors

dead_reckoning_heading_error = atan2( ...
    sin(dead_reckoning.heading - truth.heading), ...
    cos(dead_reckoning.heading - truth.heading));

ekf_heading_error = atan2( ...
    sin(ekf.heading - truth.heading), ...
    cos(ekf.heading - truth.heading));

%% Calculate bias-estimation errors

accelerometer_bias_x_error = ...
    ekf.accelerometer_bias_x ...
    - imu.accelerometer_bias_x;

accelerometer_bias_y_error = ...
    ekf.accelerometer_bias_y ...
    - imu.accelerometer_bias_y;

gyroscope_bias_error = ...
    ekf.gyroscope_bias ...
    - imu.gyroscope_bias;

%% Define GPS outage intervals

outage_start = gps_config.outage_windows(1, 1);
outage_end = gps_config.outage_windows(1, 2);

outage_mask = ...
    truth.time >= outage_start ...
    & truth.time < outage_end;

post_outage_mask = ...
    truth.time >= outage_end;

last_outage_index = find( ...
    truth.time < outage_end, ...
    1, ...
    'last');

first_recovery_index = find( ...
    truth.time >= outage_end, ...
    1, ...
    'first');

if isempty(last_outage_index)
    error('Could not determine the final GPS-outage sample.');
end

if isempty(first_recovery_index)
    error('Could not determine the first GPS-recovery sample.');
end

%% Calculate navigation performance metrics

dead_reckoning_position_rmse = ...
    sqrt(mean(dead_reckoning_position_error.^2));

ekf_position_rmse = ...
    sqrt(mean(ekf_position_error.^2));

dead_reckoning_velocity_rmse = ...
    sqrt(mean(dead_reckoning_velocity_error.^2));

ekf_velocity_rmse = ...
    sqrt(mean(ekf_velocity_error.^2));

dead_reckoning_heading_rmse = ...
    sqrt(mean( ...
        rad2deg(dead_reckoning_heading_error).^2));

ekf_heading_rmse = ...
    sqrt(mean( ...
        rad2deg(ekf_heading_error).^2));

%% Calculate corrected GPS-outage metrics

maximum_outage_position_error = ...
    max(ekf_position_error(outage_mask));

position_error_before_gps_return = ...
    ekf_position_error(last_outage_index);

position_error_after_gps_return = ...
    ekf_position_error(first_recovery_index);

maximum_post_outage_position_error = ...
    max(ekf_position_error(post_outage_mask));

gps_recovery_error_reduction = ...
    position_error_before_gps_return ...
    - position_error_after_gps_return;

if position_error_before_gps_return > 0

    gps_recovery_error_reduction_percent = ...
        100 ...
        * gps_recovery_error_reduction ...
        / position_error_before_gps_return;

else

    gps_recovery_error_reduction_percent = 0;
end

%% Innovation statistics

valid_nis = ...
    ekf.normalized_innovation_squared( ...
        ekf.gps_update_applied);

mean_nis = mean(valid_nis);

nis_95_threshold = 5.991;

nis_exceedance_count = ...
    nnz(valid_nis > nis_95_threshold);

nis_exceedance_percentage = ...
    100 ...
    * nis_exceedance_count ...
    / numel(valid_nis);

%% Bias-estimation RMSE

accelerometer_bias_x_rmse = ...
    sqrt(mean(accelerometer_bias_x_error.^2));

accelerometer_bias_y_rmse = ...
    sqrt(mean(accelerometer_bias_y_error.^2));

gyroscope_bias_rmse_deg_per_second = ...
    sqrt(mean( ...
        rad2deg(gyroscope_bias_error).^2));

