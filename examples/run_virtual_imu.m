%% Automatic Phase 2 validation

number_of_samples = numel(truth.time);

assert( ...
    numel(imu.acceleration_x_measured) == number_of_samples, ...
    'Accelerometer X sample count is incorrect.');

assert( ...
    numel(imu.acceleration_y_measured) == number_of_samples, ...
    'Accelerometer Y sample count is incorrect.');

assert( ...
    numel(imu.yaw_rate_measured) == number_of_samples, ...
    'Gyroscope sample count is incorrect.');

assert( ...
    all(isfinite(imu.acceleration_x_measured)), ...
    'Accelerometer X contains NaN or Inf values.');

assert( ...
    all(isfinite(imu.acceleration_y_measured)), ...
    'Accelerometer Y contains NaN or Inf values.');

assert( ...
    all(isfinite(imu.yaw_rate_measured)), ...
    'Gyroscope measurements contain NaN or Inf values.');

assert( ...
    abs( ...
        imu.accelerometer_bias_x(1) ...
        - imu_config.accelerometer.initial_bias_x) < 1e-12, ...
    'Accelerometer X initial bias is incorrect.');

assert( ...
    abs( ...
        imu.accelerometer_bias_y(1) ...
        - imu_config.accelerometer.initial_bias_y) < 1e-12, ...
    'Accelerometer Y initial bias is incorrect.');

assert( ...
    abs( ...
        imu.gyroscope_bias(1) ...
        - imu_config.gyroscope.initial_bias) < 1e-12, ...
    'Gyroscope initial bias is incorrect.');

accelerometer_x_model_residual = ...
    imu.acceleration_x_measured ...
    - truth.acceleration_body_x ...
    - imu.accelerometer_bias_x ...
    - imu.accelerometer_noise_x;

accelerometer_y_model_residual = ...
    imu.acceleration_y_measured ...
    - truth.acceleration_body_y ...
    - imu.accelerometer_bias_y ...
    - imu.accelerometer_noise_y;

gyroscope_model_residual = ...
    imu.yaw_rate_measured ...
    - truth.yaw_rate ...
    - imu.gyroscope_bias ...
    - imu.gyroscope_noise;

assert( ...
    max(abs(accelerometer_x_model_residual)) < 1e-12, ...
    'Accelerometer X measurement equation is inconsistent.');

assert( ...
    max(abs(accelerometer_y_model_residual)) < 1e-12, ...
    'Accelerometer Y measurement equation is inconsistent.');

assert( ...
    max(abs(gyroscope_model_residual)) < 1e-12, ...
    'Gyroscope measurement equation is inconsistent.');

accelerometer_x_noise_relative_error = ...
    abs( ...
        accelerometer_noise_x_std ...
        - imu_config.accelerometer.measurement_noise_std_x) ...
    / imu_config.accelerometer.measurement_noise_std_x;

accelerometer_y_noise_relative_error = ...
    abs( ...
        accelerometer_noise_y_std ...
        - imu_config.accelerometer.measurement_noise_std_y) ...
    / imu_config.accelerometer.measurement_noise_std_y;

gyroscope_noise_relative_error = ...
    abs( ...
        gyroscope_noise_std ...
        - imu_config.gyroscope.measurement_noise_std) ...
    / imu_config.gyroscope.measurement_noise_std;

assert( ...
    accelerometer_x_noise_relative_error < 0.15, ...
    'Accelerometer X noise standard deviation is unexpected.');

assert( ...
    accelerometer_y_noise_relative_error < 0.15, ...
    'Accelerometer Y noise standard deviation is unexpected.');

assert( ...
    gyroscope_noise_relative_error < 0.15, ...
    'Gyroscope noise standard deviation is unexpected.');

fprintf('\nAll Phase 2 validation checks passed successfully.\n');

