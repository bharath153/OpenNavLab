    ekf.accelerometer_bias_x(end));

fprintf('  True accelerometer X bias:      %.6f m/s^2\n', ...
    imu.accelerometer_bias_x(end));

fprintf('  Estimated accelerometer Y bias: %.6f m/s^2\n', ...
    ekf.accelerometer_bias_y(end));

fprintf('  True accelerometer Y bias:      %.6f m/s^2\n', ...
    imu.accelerometer_bias_y(end));

fprintf('  Estimated gyroscope bias: %.6f deg/s\n', ...
    rad2deg(ekf.gyroscope_bias(end)));

fprintf('  True gyroscope bias:      %.6f deg/s\n', ...
    rad2deg(imu.gyroscope_bias(end)));

fprintf('\nBias-estimation RMSE:\n');

fprintf('  Accelerometer X bias RMSE: %.6f m/s^2\n', ...
    accelerometer_bias_x_rmse);

fprintf('  Accelerometer Y bias RMSE: %.6f m/s^2\n', ...
    accelerometer_bias_y_rmse);

fprintf('  Gyroscope bias RMSE:       %.6f deg/s\n', ...
    gyroscope_bias_rmse_deg_per_second);

fprintf('\nInnovation consistency:\n');

fprintf('  Mean normalized innovation squared: %.4f\n', ...
    mean_nis);

fprintf('  NIS samples above 95%% threshold:    %d of %d\n', ...
    nis_exceedance_count, ...
    numel(valid_nis));

fprintf('  NIS exceedance percentage:          %.2f %%\n', ...
    nis_exceedance_percentage);

%% Automatic validation

assert( ...
    ekf.number_of_gps_updates ...
    == gps.number_of_available_measurements, ...
    'The EKF GPS update count is incorrect.');

assert( ...
    all(isfinite(ekf.position_x)), ...
    'EKF X position contains invalid values.');

assert( ...
    all(isfinite(ekf.position_y)), ...
    'EKF Y position contains invalid values.');

assert( ...
    all(isfinite(ekf.velocity_x)), ...
    'EKF X velocity contains invalid values.');

assert( ...
    all(isfinite(ekf.velocity_y)), ...
    'EKF Y velocity contains invalid values.');

assert( ...
    all(isfinite(ekf.heading)), ...
    'EKF heading contains invalid values.');

assert( ...
    all(isfinite(valid_nis)), ...
    'Valid NIS values contain NaN or Inf.');

assert( ...
    ekf_position_rmse < dead_reckoning_position_rmse, ...
    'The EKF did not improve position RMSE.');

assert( ...
    ekf_position_error(end) ...
    < dead_reckoning_position_error(end), ...
    'The EKF did not improve final position accuracy.');

assert( ...
    ekf_velocity_rmse < dead_reckoning_velocity_rmse, ...
    'The EKF did not improve velocity RMSE.');

assert( ...
    position_error_after_gps_return ...
    < position_error_before_gps_return, ...
    ['The first returning GPS measurement did not reduce ' ...
     'the position error.']);

assert( ...
    gps_recovery_error_reduction_percent > 0, ...
    'The calculated GPS recovery improvement is invalid.');

for sample_index = 1:numel(truth.time)

    current_covariance = ...
        ekf.covariance_history(:, :, sample_index);

    covariance_asymmetry = max( ...
        abs(current_covariance - current_covariance'), ...
        [], ...
        'all');

    assert( ...
        covariance_asymmetry ...
        < ekf_config.covariance_symmetry_tolerance, ...
        'The EKF covariance matrix lost symmetry.');

    assert( ...
        all( ...
            diag(current_covariance) ...
            > ekf_config.minimum_variance_tolerance), ...
        'The EKF covariance contains negative variances.');
end

