%% Run Monte Carlo sensitivity study

study_timer = tic;
result_index = 0;

for current_run = 1:number_of_runs

    %% Generate common initialization errors

    initialization_seed = ...
        study_config.initialization_seed_offset ...
        + current_run;

    rng(initialization_seed, 'twister');

    initial_position_error_x = ...
        study_config.initial_position_error_std_x ...
        * randn();

    initial_position_error_y = ...
        study_config.initial_position_error_std_y ...
        * randn();

    initial_velocity_error_x = ...
        study_config.initial_velocity_error_std_x ...
        * randn();

    initial_velocity_error_y = ...
        study_config.initial_velocity_error_std_y ...
        * randn();

    initial_heading_error = ...
        study_config.initial_heading_error_std ...
        * randn();

    true_accelerometer_bias_variation_x = ...
        study_config ...
        .true_accelerometer_bias_variation_std_x ...
        * randn();

    true_accelerometer_bias_variation_y = ...
        study_config ...
        .true_accelerometer_bias_variation_std_y ...
        * randn();

    true_gyroscope_bias_variation = ...
        study_config ...
        .true_gyroscope_bias_variation_std ...
        * randn();

    %% Generate one common IMU realization

    imu_config = base_imu_config;

    imu_config.random_seed = ...
        study_config.imu_seed_offset ...
        + current_run;

    imu_config.accelerometer.initial_bias_x = ...
        base_imu_config.accelerometer.initial_bias_x ...
        + true_accelerometer_bias_variation_x;

    imu_config.accelerometer.initial_bias_y = ...
        base_imu_config.accelerometer.initial_bias_y ...
        + true_accelerometer_bias_variation_y;

    imu_config.gyroscope.initial_bias = ...
        base_imu_config.gyroscope.initial_bias ...
        + true_gyroscope_bias_variation;

    imu = simulate_imu( ...
        truth, ...
        imu_config);

    %% Generate one complete GPS realization
    %
    % All outage-duration cases in this Monte Carlo run use the same GPS
    % noise realization. Measurements are removed only after generation.

    gps_full_config = base_gps_config;

    gps_full_config.random_seed = ...
        study_config.gps_seed_offset ...
        + current_run;

    gps_full_config.outage_windows = [];

    gps_full = simulate_gps( ...
        truth, ...
        gps_full_config);

    %% Create common imperfect EKF initial state

    initial_state.position_x = ...
        truth.position_x(1) ...
        + initial_position_error_x;

    initial_state.position_y = ...
        truth.position_y(1) ...
        + initial_position_error_y;

    initial_state.velocity_x = ...
        truth.velocity_x(1) ...
        + initial_velocity_error_x;

    initial_state.velocity_y = ...
        truth.velocity_y(1) ...
        + initial_velocity_error_y;

    initial_heading_unwrapped = ...
        truth.heading(1) ...
        + initial_heading_error;

    initial_state.heading = atan2( ...
        sin(initial_heading_unwrapped), ...
        cos(initial_heading_unwrapped));

    % The EKF does not know the true sensor biases.
    initial_state.accelerometer_bias_x = 0;
    initial_state.accelerometer_bias_y = 0;
    initial_state.gyroscope_bias = 0;

    %% Run each outage-duration case

    for duration_index = 1:number_of_durations

        current_duration = ...
            outage_durations(duration_index);

        current_outage_end_time = ...
            outage_start_time ...
            + current_duration;

        %% Apply duration-specific outage

        gps = apply_outage_to_gps( ...
            gps_full, ...
            truth.time, ...
            outage_start_time, ...
            current_duration);

        %% Configure and run EKF

        ekf_config = create_ekf_config( ...
            imu_config, ...
            gps.config);

        ekf = run_ekf_navigation( ...
            imu, ...
            gps, ...
            initial_state, ...
            ekf_config);

        %% Calculate navigation errors

        current_position_error = hypot( ...
            ekf.position_x - truth.position_x, ...
            ekf.position_y - truth.position_y);

        current_velocity_error = hypot( ...
            ekf.velocity_x - truth.velocity_x, ...
            ekf.velocity_y - truth.velocity_y);

        current_heading_error = atan2( ...
            sin(ekf.heading - truth.heading), ...
            cos(ekf.heading - truth.heading));

        current_heading_error_degrees = ...
            rad2deg(current_heading_error);

        %% Determine interval-end evaluation index

        if current_duration > 0

            current_outage_mask = ...
                truth.time >= outage_start_time ...
                & truth.time < current_outage_end_time;

            final_interval_index = find( ...
                current_outage_mask, ...
                1, ...
                'last');

            if isempty(final_interval_index)

                error( ...
                    ['No simulation samples were found inside the ' ...
                     '%.1f-second GPS outage.'], ...
                    current_duration);
            end

            current_reference_or_maximum_error = ...
                max( ...
                    current_position_error( ...
                        current_outage_mask));

            current_is_baseline = false;

        else

            % No-outage baseline evaluated at the nominal outage start time.
            final_interval_index = find( ...
                truth.time >= outage_start_time, ...
                1, ...
                'first');

            if isempty(final_interval_index)

                error( ...
                    'Could not locate the no-outage evaluation sample.');
            end

            current_reference_or_maximum_error = ...
                current_position_error(final_interval_index);

            current_is_baseline = true;
        end

        %% Calculate position-covariance ellipse

        position_indices = ...
            [ekf_config.index.position_x, ...
             ekf_config.index.position_y];

        position_covariance = ...
            ekf.covariance_history( ...
                position_indices, ...
                position_indices, ...
                final_interval_index);

        position_covariance = ...
            0.5 ...
            * (position_covariance ...
            + position_covariance');

        covariance_eigenvalues = ...
            eig(position_covariance);

        covariance_eigenvalues = ...
            max(covariance_eigenvalues, 0);

        current_three_sigma_major_axis = ...
            3 ...
            * sqrt(max(covariance_eigenvalues));

        %% Calculate innovation statistics

        valid_nis = ...
            ekf.normalized_innovation_squared( ...
                ekf.gps_update_applied);

        current_mean_nis = ...
            mean(valid_nis);

        current_nis_exceedance_percentage = ...
            100 ...
            * nnz(valid_nis > 5.991) ...
            / numel(valid_nis);

        %% Store scalar results

        result_index = result_index + 1;

        run_number(result_index) = ...
            current_run;

        outage_duration(result_index) = ...
            current_duration;

        outage_end_time(result_index) = ...
            current_outage_end_time;

        is_no_outage_baseline(result_index) = ...
            current_is_baseline;

        position_rmse(result_index) = ...
            sqrt(mean(current_position_error.^2));

        velocity_rmse(result_index) = ...
            sqrt(mean(current_velocity_error.^2));

        heading_rmse(result_index) = ...
            sqrt(mean(current_heading_error_degrees.^2));

        final_position_error(result_index) = ...
            current_position_error(end);

        reference_or_maximum_position_error(result_index) = ...
            current_reference_or_maximum_error;

        end_interval_position_error(result_index) = ...
            current_position_error(final_interval_index);

        end_interval_velocity_error(result_index) = ...
            current_velocity_error(final_interval_index);

        end_interval_heading_error(result_index) = ...
            abs( ...
                current_heading_error_degrees( ...
                    final_interval_index));

        position_three_sigma_major_axis(result_index) = ...
            current_three_sigma_major_axis;

        mean_nis(result_index) = ...
            current_mean_nis;

        nis_exceedance_percentage(result_index) = ...
            current_nis_exceedance_percentage;

        number_of_gps_updates(result_index) = ...
            ekf.number_of_gps_updates;
    end

    %% Progress report

    if mod( ...
            current_run, ...
            study_config.progress_report_interval) == 0 ...
            || current_run == number_of_runs

        elapsed_time = toc(study_timer);

        fprintf( ...
            ['  Completed %d of %d Monte Carlo runs ' ...
             '— elapsed %.1f s\n'], ...
            current_run, ...
            number_of_runs, ...
            elapsed_time);
    end
end

