study_timer = tic;

%% Monte Carlo loop

for current_run = 1:number_of_runs

    %% Generate common random initialization conditions

    initialization_seed = ...
        study_config.initialization_seed_offset ...
        + current_run;

    rng(initialization_seed, 'twister');

    initial_position_error_x = ...
        study_config.initial_position_error_std_x ...
        * randn();

    initial_position_error_y = ...
        study_config.initial_position_error_std_y ...
        * randn();

    initial_velocity_error_x = ...
        study_config.initial_velocity_error_std_x ...
        * randn();

    initial_velocity_error_y = ...
        study_config.initial_velocity_error_std_y ...
        * randn();

    initial_heading_error = ...
        study_config.initial_heading_error_std ...
        * randn();

    mems_bias_variation_x = ...
        study_config ...
        .mems_accelerometer_bias_variation_std_x ...
        * randn();

    mems_bias_variation_y = ...
        study_config ...
        .mems_accelerometer_bias_variation_std_y ...
        * randn();

    mems_gyro_bias_variation = ...
        study_config ...
        .mems_gyroscope_bias_variation_std ...
        * randn();

    quantum_calibration_error_x = ...
        study_config ...
        .quantum_accelerometer_calibration_error_std_x ...
        * randn();

    quantum_calibration_error_y = ...
        study_config ...
        .quantum_accelerometer_calibration_error_std_y ...
        * randn();

    quantum_gyro_calibration_error = ...
        study_config ...
        .quantum_gyroscope_calibration_error_std ...
        * randn();

    %% Simulate common MEMS IMU

    imu_config = base_imu_config;

    imu_config.random_seed = ...
        study_config.imu_seed_offset ...
        + current_run;

    imu_config.accelerometer.initial_bias_x = ...
        base_imu_config.accelerometer.initial_bias_x ...
        + mems_bias_variation_x;

    imu_config.accelerometer.initial_bias_y = ...
        base_imu_config.accelerometer.initial_bias_y ...
        + mems_bias_variation_y;

    imu_config.gyroscope.initial_bias = ...
        base_imu_config.gyroscope.initial_bias ...
        + mems_gyro_bias_variation;

    imu = simulate_imu( ...
        truth, ...
        imu_config);

    %% Simulate common GPS measurements

    gps_config = base_gps_config;

    gps_config.random_seed = ...
        study_config.gps_seed_offset ...
        + current_run;

    gps = simulate_gps( ...
        truth, ...
        gps_config);

    %% Simulate quantum reference
    %
    % The actual sensor receives a small calibration offset. The
    % quantum-aided EKF will continue to use the nominal calibration from
    % base_quantum_config.

    actual_quantum_config = ...
        base_quantum_config;

    actual_quantum_config.random_seed = ...
        study_config.quantum_seed_offset ...
        + current_run;

    actual_quantum_config.accelerometer.initial_bias_x = ...
        base_quantum_config.accelerometer.initial_bias_x ...
        + quantum_calibration_error_x;

    actual_quantum_config.accelerometer.initial_bias_y = ...
        base_quantum_config.accelerometer.initial_bias_y ...
        + quantum_calibration_error_y;

    actual_quantum_config.gyroscope.initial_bias = ...
        base_quantum_config.gyroscope.initial_bias ...
        + quantum_gyro_calibration_error;

    quantum = simulate_quantum_reference_imu( ...
        truth, ...
        actual_quantum_config);

    %% Common imperfect initial state

    initial_state.position_x = ...
        truth.position_x(1) ...
        + initial_position_error_x;

    initial_state.position_y = ...
        truth.position_y(1) ...
        + initial_position_error_y;

    initial_state.velocity_x = ...
        truth.velocity_x(1) ...
        + initial_velocity_error_x;

    initial_state.velocity_y = ...
        truth.velocity_y(1) ...
        + initial_velocity_error_y;

    initial_heading_unwrapped = ...
        truth.heading(1) ...
        + initial_heading_error;

    initial_state.heading = atan2( ...
        sin(initial_heading_unwrapped), ...
        cos(initial_heading_unwrapped));

    initial_state.accelerometer_bias_x = 0;
    initial_state.accelerometer_bias_y = 0;
    initial_state.gyroscope_bias = 0;

    %% Run classical GPS/MEMS EKF

    classical_config = create_ekf_config( ...
        imu_config, ...
        gps_config);

    classical_ekf = run_ekf_navigation( ...
        imu, ...
        gps, ...
        initial_state, ...
        classical_config);

    %% Run GPS/MEMS/quantum EKF
    %
    % The base quantum configuration supplies the nominal calibrated
    % quantum biases to the filter.

    quantum_aided_config = ...
        create_quantum_aided_ekf_config( ...
            imu_config, ...
            gps_config, ...
            base_quantum_config);

    quantum_aided_ekf = ...
        run_quantum_aided_ekf_navigation( ...
            imu, ...
            gps, ...
            quantum, ...
            initial_state, ...
            quantum_aided_config);

    %% Calculate navigation errors

    current_classical_position_error = hypot( ...
        classical_ekf.position_x - truth.position_x, ...
        classical_ekf.position_y - truth.position_y);

    current_quantum_position_error = hypot( ...
        quantum_aided_ekf.position_x - truth.position_x, ...
        quantum_aided_ekf.position_y - truth.position_y);

    current_classical_velocity_error = hypot( ...
        classical_ekf.velocity_x - truth.velocity_x, ...
        classical_ekf.velocity_y - truth.velocity_y);

    current_quantum_velocity_error = hypot( ...
        quantum_aided_ekf.velocity_x - truth.velocity_x, ...
        quantum_aided_ekf.velocity_y - truth.velocity_y);

    current_classical_heading_error = atan2( ...
        sin(classical_ekf.heading - truth.heading), ...
        cos(classical_ekf.heading - truth.heading));

    current_quantum_heading_error = atan2( ...
        sin(quantum_aided_ekf.heading - truth.heading), ...
        cos(quantum_aided_ekf.heading - truth.heading));

    current_classical_heading_error_degrees = ...
        rad2deg(current_classical_heading_error);

    current_quantum_heading_error_degrees = ...
        rad2deg(current_quantum_heading_error);

    %% Locate first available GPS update after the outage

    first_recovery_index = find( ...
        gps.available_measurement_mask ...
        & truth.time >= outage_end_time, ...
        1, ...
        'first');

    if isempty(first_recovery_index)

        error( ...
            'No GPS recovery measurement was found in run %d.', ...
            current_run);
    end

    %% Overall navigation metrics

    classical_position_rmse(current_run) = ...
        sqrt(mean(current_classical_position_error.^2));

    quantum_position_rmse(current_run) = ...
        sqrt(mean(current_quantum_position_error.^2));

    classical_velocity_rmse(current_run) = ...
        sqrt(mean(current_classical_velocity_error.^2));

    quantum_velocity_rmse(current_run) = ...
        sqrt(mean(current_quantum_velocity_error.^2));

    classical_heading_rmse(current_run) = ...
        sqrt(mean(current_classical_heading_error_degrees.^2));

    quantum_heading_rmse(current_run) = ...
        sqrt(mean(current_quantum_heading_error_degrees.^2));

    %% GPS-outage position metrics

    classical_maximum_outage_error(current_run) = ...
        max(current_classical_position_error(outage_mask));

    quantum_maximum_outage_error(current_run) = ...
        max(current_quantum_position_error(outage_mask));

    classical_end_outage_error(current_run) = ...
        current_classical_position_error(last_outage_index);

    quantum_end_outage_error(current_run) = ...
        current_quantum_position_error(last_outage_index);

    classical_error_after_gps_return(current_run) = ...
        current_classical_position_error(first_recovery_index);

    quantum_error_after_gps_return(current_run) = ...
        current_quantum_position_error(first_recovery_index);

    classical_final_position_error(current_run) = ...
        current_classical_position_error(end);

    quantum_final_position_error(current_run) = ...
        current_quantum_position_error(end);

    %% MEMS-bias estimation errors

    classical_bias_x_error = ...
        classical_ekf.accelerometer_bias_x ...
        - imu.accelerometer_bias_x;

    quantum_bias_x_error = ...
        quantum_aided_ekf.accelerometer_bias_x ...
        - imu.accelerometer_bias_x;

    classical_bias_y_error = ...
        classical_ekf.accelerometer_bias_y ...
        - imu.accelerometer_bias_y;

    quantum_bias_y_error = ...
        quantum_aided_ekf.accelerometer_bias_y ...
        - imu.accelerometer_bias_y;

    classical_gyro_bias_error_degrees = ...
        rad2deg( ...
            classical_ekf.gyroscope_bias ...
            - imu.gyroscope_bias);

    quantum_gyro_bias_error_degrees = ...
        rad2deg( ...
            quantum_aided_ekf.gyroscope_bias ...
            - imu.gyroscope_bias);

    %% Full-trajectory bias RMSE

    classical_bias_x_rmse(current_run) = ...
        sqrt(mean(classical_bias_x_error.^2));

    quantum_bias_x_rmse(current_run) = ...
        sqrt(mean(quantum_bias_x_error.^2));

    classical_bias_y_rmse(current_run) = ...
        sqrt(mean(classical_bias_y_error.^2));

    quantum_bias_y_rmse(current_run) = ...
        sqrt(mean(quantum_bias_y_error.^2));

    classical_gyro_bias_rmse_deg_per_second(current_run) = ...
        sqrt(mean(classical_gyro_bias_error_degrees.^2));

    quantum_gyro_bias_rmse_deg_per_second(current_run) = ...
        sqrt(mean(quantum_gyro_bias_error_degrees.^2));

    %% GPS-outage bias RMSE

    classical_outage_bias_x_rmse(current_run) = ...
        sqrt(mean( ...
            classical_bias_x_error(outage_mask).^2));

    quantum_outage_bias_x_rmse(current_run) = ...
        sqrt(mean( ...
            quantum_bias_x_error(outage_mask).^2));

    classical_outage_bias_y_rmse(current_run) = ...
        sqrt(mean( ...
            classical_bias_y_error(outage_mask).^2));

    quantum_outage_bias_y_rmse(current_run) = ...
        sqrt(mean( ...
            quantum_bias_y_error(outage_mask).^2));

    classical_outage_gyro_bias_rmse_deg_per_second(current_run) = ...
        sqrt(mean( ...
            classical_gyro_bias_error_degrees(outage_mask).^2));

    quantum_outage_gyro_bias_rmse_deg_per_second(current_run) = ...
        sqrt(mean( ...
            quantum_gyro_bias_error_degrees(outage_mask).^2));

    %% Paired performance improvements

    outage_error_reduction(current_run) = ...
        classical_maximum_outage_error(current_run) ...
        - quantum_maximum_outage_error(current_run);

    outage_error_reduction_percent(current_run) = ...
        100 ...
        * outage_error_reduction(current_run) ...
        / max( ...
            classical_maximum_outage_error(current_run), ...
            eps);

    position_rmse_reduction(current_run) = ...
        classical_position_rmse(current_run) ...
        - quantum_position_rmse(current_run);

    position_rmse_reduction_percent(current_run) = ...
        100 ...
        * position_rmse_reduction(current_run) ...
        / max(classical_position_rmse(current_run), eps);

    velocity_rmse_reduction_percent(current_run) = ...
        100 ...
        * ( ...
            classical_velocity_rmse(current_run) ...
            - quantum_velocity_rmse(current_run)) ...
        / max(classical_velocity_rmse(current_run), eps);

    heading_rmse_reduction_percent(current_run) = ...
        100 ...
        * ( ...
            classical_heading_rmse(current_run) ...
            - quantum_heading_rmse(current_run)) ...
        / max(classical_heading_rmse(current_run), eps);

    %% GPS innovation statistics

    valid_classical_gps_nis = ...
        classical_ekf.normalized_innovation_squared( ...
            classical_ekf.gps_update_applied);

    valid_quantum_gps_nis = ...
        quantum_aided_ekf ...
        .gps_normalized_innovation_squared( ...
            quantum_aided_ekf.gps_update_applied);

    valid_quantum_update_nis = ...
        quantum_aided_ekf ...
        .quantum_normalized_innovation_squared( ...
            quantum_aided_ekf.quantum_update_applied);

    classical_gps_mean_nis(current_run) = ...
        mean(valid_classical_gps_nis);

    quantum_gps_mean_nis(current_run) = ...
        mean(valid_quantum_gps_nis);

    quantum_update_mean_nis(current_run) = ...
        mean(valid_quantum_update_nis);

    classical_gps_nis_exceedance_percentage(current_run) = ...
        100 ...
        * nnz( ...
            valid_classical_gps_nis ...
            > study_config.gps_nis_95_threshold) ...
        / numel(valid_classical_gps_nis);

    quantum_gps_nis_exceedance_percentage(current_run) = ...
        100 ...
        * nnz( ...
            valid_quantum_gps_nis ...
            > study_config.gps_nis_95_threshold) ...
        / numel(valid_quantum_gps_nis);

    quantum_update_nis_exceedance_percentage(current_run) = ...
        100 ...
        * nnz( ...
            valid_quantum_update_nis ...
            > study_config.quantum_nis_95_threshold) ...
        / numel(valid_quantum_update_nis);

    %% Store update counts

    classical_gps_update_count(current_run) = ...
        classical_ekf.number_of_gps_updates;

    quantum_gps_update_count(current_run) = ...
        quantum_aided_ekf.number_of_gps_updates;

    quantum_update_count(current_run) = ...
        quantum_aided_ekf.number_of_quantum_updates;

    %% Progress report

    if mod( ...
            current_run, ...
            study_config.progress_report_interval) == 0 ...
            || current_run == number_of_runs

        elapsed_time = toc(study_timer);

        fprintf( ...
            ['  Completed %d of %d paired runs ' ...
             '— elapsed %.1f s\n'], ...
            current_run, ...
            number_of_runs, ...
            elapsed_time);
    end
end

