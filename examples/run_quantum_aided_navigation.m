clear;
clc;
close all;

%% Identify project folders

current_script = mfilename('fullpath');
examples_folder = fileparts(current_script);
project_root = fileparts(examples_folder);

trajectory_source_folder = ...
    fullfile(project_root, 'src', 'trajectory');

sensor_source_folder = ...
    fullfile(project_root, 'src', 'sensors');

filter_source_folder = ...
    fullfile(project_root, 'src', 'filters');

config_folder = ...
    fullfile(project_root, 'config');

results_folder = ...
    fullfile(project_root, 'results');

figure_folder = ...
    fullfile(results_folder, 'figures');

data_folder = ...
    fullfile(results_folder, 'data');

%% Add source folders

addpath(trajectory_source_folder);
addpath(sensor_source_folder);
addpath(filter_source_folder);
addpath(config_folder);

%% Create output folders

if ~exist(results_folder, 'dir')
    mkdir(results_folder);
end

if ~exist(figure_folder, 'dir')
    mkdir(figure_folder);
end

if ~exist(data_folder, 'dir')
    mkdir(data_folder);
end

%% Generate ground truth

dt = 0.01;
simulation_time = 120;

truth = generate_truth_trajectory( ...
    dt, ...
    simulation_time);

%% Configure and simulate sensors

imu_config = create_imu_config();
gps_config = create_gps_config();

% Explicit 20-second GPS outage.
gps_config.outage_windows = ...
    [50, 70];

quantum_config = ...
    create_quantum_sensor_config();

quantum_config.outage_windows = [];

imu = simulate_imu( ...
    truth, ...
    imu_config);

gps = simulate_gps( ...
    truth, ...
    gps_config);

quantum = simulate_quantum_reference_imu( ...
    truth, ...
    quantum_config);

%% Common initial state

initial_state.position_x = ...
    truth.position_x(1);

initial_state.position_y = ...
    truth.position_y(1);

initial_state.velocity_x = ...
    truth.velocity_x(1);

initial_state.velocity_y = ...
    truth.velocity_y(1);

initial_state.heading = ...
    truth.heading(1);

% Neither filter is supplied with the true MEMS biases.
initial_state.accelerometer_bias_x = 0;
initial_state.accelerometer_bias_y = 0;
initial_state.gyroscope_bias = 0;

%% Classical GPS/MEMS EKF

classical_config = create_ekf_config( ...
    imu_config, ...
    gps_config);

classical_ekf = run_ekf_navigation( ...
    imu, ...
    gps, ...
    initial_state, ...
    classical_config);

%% Quantum-aided GPS/MEMS EKF

quantum_aided_config = ...
    create_quantum_aided_ekf_config( ...
        imu_config, ...
        gps_config, ...
        quantum_config);

quantum_aided_ekf = ...
    run_quantum_aided_ekf_navigation( ...
        imu, ...
        gps, ...
        quantum, ...
        initial_state, ...
        quantum_aided_config);

%% Calculate navigation errors

classical_position_error = hypot( ...
    classical_ekf.position_x - truth.position_x, ...
    classical_ekf.position_y - truth.position_y);

quantum_position_error = hypot( ...
    quantum_aided_ekf.position_x - truth.position_x, ...
    quantum_aided_ekf.position_y - truth.position_y);

classical_velocity_error = hypot( ...
    classical_ekf.velocity_x - truth.velocity_x, ...
    classical_ekf.velocity_y - truth.velocity_y);

quantum_velocity_error = hypot( ...
    quantum_aided_ekf.velocity_x - truth.velocity_x, ...
    quantum_aided_ekf.velocity_y - truth.velocity_y);

classical_heading_error = atan2( ...
    sin(classical_ekf.heading - truth.heading), ...
    cos(classical_ekf.heading - truth.heading));

quantum_heading_error = atan2( ...
    sin(quantum_aided_ekf.heading - truth.heading), ...
    cos(quantum_aided_ekf.heading - truth.heading));

classical_heading_error_degrees = ...
    rad2deg(classical_heading_error);

quantum_heading_error_degrees = ...
    rad2deg(quantum_heading_error);

%% GPS-outage indices

outage_start = ...
    gps_config.outage_windows(1, 1);

outage_end = ...
    gps_config.outage_windows(1, 2);

outage_mask = ...
    truth.time >= outage_start ...
    & truth.time < outage_end;

last_outage_index = find( ...
    truth.time < outage_end, ...
    1, ...
    'last');

first_recovery_index = find( ...
    truth.time >= outage_end, ...
    1, ...
    'first');

%% Performance metrics

classical_position_rmse = ...
    sqrt(mean(classical_position_error.^2));

quantum_position_rmse = ...
    sqrt(mean(quantum_position_error.^2));

classical_velocity_rmse = ...
    sqrt(mean(classical_velocity_error.^2));

quantum_velocity_rmse = ...
    sqrt(mean(quantum_velocity_error.^2));

classical_heading_rmse = ...
    sqrt(mean(classical_heading_error_degrees.^2));

quantum_heading_rmse = ...
    sqrt(mean(quantum_heading_error_degrees.^2));

classical_maximum_outage_error = ...
    max(classical_position_error(outage_mask));

quantum_maximum_outage_error = ...
    max(quantum_position_error(outage_mask));

classical_error_before_gps_return = ...
    classical_position_error(last_outage_index);

quantum_error_before_gps_return = ...
    quantum_position_error(last_outage_index);

classical_error_after_gps_return = ...
    classical_position_error(first_recovery_index);

quantum_error_after_gps_return = ...
    quantum_position_error(first_recovery_index);

maximum_outage_improvement = ...
    classical_maximum_outage_error ...
    - quantum_maximum_outage_error;

if classical_maximum_outage_error > 0

    maximum_outage_improvement_percent = ...
        100 ...
        * maximum_outage_improvement ...
        / classical_maximum_outage_error;

else

    maximum_outage_improvement_percent = 0;
end

%% Final MEMS-bias errors

classical_bias_x_error_final = ...
    classical_ekf.accelerometer_bias_x(end) ...
    - imu.accelerometer_bias_x(end);

quantum_bias_x_error_final = ...
    quantum_aided_ekf.accelerometer_bias_x(end) ...
    - imu.accelerometer_bias_x(end);

classical_bias_y_error_final = ...
    classical_ekf.accelerometer_bias_y(end) ...
    - imu.accelerometer_bias_y(end);

quantum_bias_y_error_final = ...
    quantum_aided_ekf.accelerometer_bias_y(end) ...
    - imu.accelerometer_bias_y(end);

classical_gyro_bias_error_final = ...
    rad2deg( ...
        classical_ekf.gyroscope_bias(end) ...
        - imu.gyroscope_bias(end));

quantum_gyro_bias_error_final = ...
    rad2deg( ...
        quantum_aided_ekf.gyroscope_bias(end) ...
        - imu.gyroscope_bias(end));

%% Quantum innovation statistics

valid_quantum_nis = ...
    quantum_aided_ekf ...
    .quantum_normalized_innovation_squared( ...
        quantum_aided_ekf.quantum_update_applied);

mean_quantum_nis = ...
    mean(valid_quantum_nis);

quantum_nis_exceedance_percentage = ...
    100 ...
    * nnz( ...
        valid_quantum_nis ...
        > quantum_aided_config.quantum.nis_95_threshold) ...
    / numel(valid_quantum_nis);

