    quantum_maximum_outage_error);

fprintf('  Absolute outage improvement:        %.4f m\n', ...
    maximum_outage_improvement);

fprintf('  Relative outage improvement:        %.2f %%\n', ...
    maximum_outage_improvement_percent);

fprintf('  Classical error before GPS return:  %.4f m\n', ...
    classical_error_before_gps_return);

fprintf('  Quantum error before GPS return:    %.4f m\n', ...
    quantum_error_before_gps_return);

fprintf('  Classical error after GPS return:   %.4f m\n', ...
    classical_error_after_gps_return);

fprintf('  Quantum error after GPS return:     %.4f m\n', ...
    quantum_error_after_gps_return);

fprintf('\nVelocity performance:\n');

fprintf('  Classical velocity RMSE:      %.4f m/s\n', ...
    classical_velocity_rmse);

fprintf('  Quantum-aided velocity RMSE:  %.4f m/s\n', ...
    quantum_velocity_rmse);

fprintf('\nHeading performance:\n');

fprintf('  Classical heading RMSE:       %.4f deg\n', ...
    classical_heading_rmse);

fprintf('  Quantum-aided heading RMSE:   %.4f deg\n', ...
    quantum_heading_rmse);

fprintf('\nFinal MEMS-bias estimation errors:\n');

fprintf('  Accelerometer X:\n');
fprintf('    Classical:     %.6f m/s^2\n', ...
    classical_bias_x_error_final);

fprintf('    Quantum-aided: %.6f m/s^2\n', ...
    quantum_bias_x_error_final);

fprintf('  Accelerometer Y:\n');
fprintf('    Classical:     %.6f m/s^2\n', ...
    classical_bias_y_error_final);

fprintf('    Quantum-aided: %.6f m/s^2\n', ...
    quantum_bias_y_error_final);

fprintf('  Gyroscope:\n');
fprintf('    Classical:     %.6f deg/s\n', ...
    classical_gyro_bias_error_final);

fprintf('    Quantum-aided: %.6f deg/s\n', ...
    quantum_gyro_bias_error_final);

fprintf('\nQuantum innovation consistency:\n');

fprintf('  Mean quantum NIS:            %.4f\n', ...
    mean_quantum_nis);

fprintf('  Expected measurement dimension: 3\n');

fprintf('  NIS samples above 95%% threshold: %.2f %%\n', ...
    quantum_nis_exceedance_percentage);

%% Automatic validation

assert( ...
    classical_ekf.number_of_gps_updates ...
    == gps.number_of_available_measurements, ...
    'Classical GPS update count is incorrect.');

assert( ...
    quantum_aided_ekf.number_of_gps_updates ...
    == gps.number_of_available_measurements, ...
    'Quantum-aided GPS update count is incorrect.');

assert( ...
    quantum_aided_ekf.number_of_quantum_updates ...
    == quantum.number_of_available_measurements, ...
    'Quantum update count is incorrect.');

assert( ...
    all(isfinite(quantum_aided_ekf.position_x)), ...
    'Quantum-aided X position contains NaN or Inf.');

assert( ...
    all(isfinite(quantum_aided_ekf.position_y)), ...
    'Quantum-aided Y position contains NaN or Inf.');

assert( ...
    all(isfinite(quantum_aided_ekf.velocity_x)), ...
    'Quantum-aided X velocity contains NaN or Inf.');

assert( ...
    all(isfinite(quantum_aided_ekf.velocity_y)), ...
    'Quantum-aided Y velocity contains NaN or Inf.');

assert( ...
    all(isfinite(quantum_aided_ekf.heading)), ...
    'Quantum-aided heading contains NaN or Inf.');

assert( ...
    all(isfinite(valid_quantum_nis)), ...
    'Quantum NIS contains NaN or Inf.');

assert( ...
    mean_quantum_nis ...
    > quantum_aided_config.quantum.minimum_allowed_mean_nis, ...
    'Mean quantum NIS is unexpectedly low.');

assert( ...
    mean_quantum_nis ...
    < quantum_aided_config.quantum.maximum_allowed_mean_nis, ...
    'Mean quantum NIS is unexpectedly high.');

if quantum_maximum_outage_error ...
        >= classical_maximum_outage_error

    warning( ...
        ['The quantum-aided EKF did not reduce the maximum outage ' ...
         'error in this single noise realization. Monte Carlo analysis ' ...
         'is required before drawing a performance conclusion.']);
end

fprintf('\nAll Phase 7B validation checks passed successfully.\n');

