save( ...
    fullfile(data_folder, 'phase1_ground_truth.mat'), ...
    'truth');

fprintf('\nGround-truth data saved to:\n%s\n', ...
    fullfile(data_folder, 'phase1_ground_truth.mat'));

fprintf('\nFigures saved to:\n%s\n', ...
    figure_folder);

fprintf('\nPhase 1 completed successfully.\n');