%% Simulation configuration

dt = 0.01;
simulation_time = 120;

%% Generate Phase 1 ground truth

truth = generate_truth_trajectory( ...
    dt, ...
    simulation_time);

%% Create virtual IMU configuration

imu_config = create_imu_config();

%% Generate virtual IMU measurements

imu = simulate_imu( ...
    truth, ...
    imu_config);

%% Calculate sensor statistics

accelerometer_noise_x_mean = ...
    mean(imu.accelerometer_noise_x);

accelerometer_noise_y_mean = ...
    mean(imu.accelerometer_noise_y);

gyroscope_noise_mean = ...
    mean(imu.gyroscope_noise);

accelerometer_noise_x_std = ...
    std(imu.accelerometer_noise_x);

accelerometer_noise_y_std = ...
    std(imu.accelerometer_noise_y);

gyroscope_noise_std = ...
    std(imu.gyroscope_noise);

accelerometer_error_x_rmse = ...
    sqrt(mean(imu.accelerometer_error_x.^2));

accelerometer_error_y_rmse = ...
    sqrt(mean(imu.accelerometer_error_y.^2));

gyroscope_error_rmse = ...
    sqrt(mean(imu.gyroscope_error.^2));

